  <h2>アラートエスカレーション階層：すべてのイベントが同等ではない</h2>
  <p>
    YumePadのアラートシステムは、アラートの緊急度を基礎となるイベントの臨床的重要性と適切な対応にマッピングする3段階エスカレーションモデルを使用している。
  </p>
  <p>
    <strong>Tier 1 — 情報提供：</strong>バイタルサインの逸脱が検出され、重複排除ウィンドウ内に解決した。通知は送信されない。イベントは翌朝のレポートに記録され、時系列のパターン分析に活用される。例：体動アーティファクト中の短時間の頻脈、REM中の一時的な呼吸不規則性。
  </p>
  <p>
    <strong>Tier 2 — ソフトアラート：</strong>バイタルサインの逸脱が重複排除ウィンドウを超えて持続しているが、臨床的緊急度の低い範囲内に留まっている。眠っている人自身のスマートフォン（設定されている場合）がアプリ内の穏やかな通知を受け取る。主要な介護者がアプリ内通知を受け取る。このTierに音を設定していない限り、音は鳴らない。通知の言葉遣いは意図的に警告的でない：<em>「心拍数がベースラインを8分間上回っています。引き続き監視中。」</em> 例：困難な夢の中の持続的な軽度頻脈、体動後の長引く上昇。
  </p>
  <p>
    <strong>Tier 3 — クリティカルアラート：</strong>バイタルサインの逸脱が事前に設定された閾値を大幅に超えるか、複数のメトリクスにわたる逸脱の組み合わせが同時に発生する。指定されたすべての介護者に、デフォルトでフル通知音が有効になっている状態で通知される。通知には特定のバイタルサイン値、継続時間、および行動推奨事項が含まれる。例：呼吸運動の長時間の不在（潜在的な重度の無呼吸イベント）、極端な心拍数の逸脱、正常な睡眠と一致しない長時間の不動状態の検出。
  </p>
  <p>
    Tier境界は設定可能であり、SleepTechはセットアップ時に協力的な家族の対話を推奨している。既知の心疾患のない45歳の人にとってのTier 3イベントは、心房細動を持つ82歳の人にとってのTier 3とは異なる。システムはエビデンスに基づいたデフォルトを提供するが、臨床的な適切性は調整における人間の判断を必要とする。
  </p>

  <h2>家族の次元：介護者と睡眠者の役割</h2>
  <p>
    アラートシステム設計の最も実際的に重要な側面——そして最もしばしば見落とされる側面——の一つは、モニタリングされている人とアラートを受け取る人または人々の区別だ。これらはしばしば同じ個人ではなく、その必要性は構造的に異なる。
  </p>
  <p>
    モニタリングされている人——通常は高齢の親、慢性疾患を持つ個人、または自分の睡眠の健康について懸念を表明した人——は、システムが本当の問題を捕捉することを知る必要がある。しかし彼らはまた、システムが押し付けがましいまたは不安を引き起こすように感じさせる方法で自分たちをモニタリングしないことを信頼する必要がある。心拍数が中央値より5拍上るたびに高齢の睡眠者に通知を送るモニタリングシステムは、健康上の価値を提供していない——健康不安を提供している。YumePadはデフォルトで、睡眠者自身がセルフモニタリングモードに明示的にオプトインしない限り、睡眠者自身のデバイスに情報提供やTier 2アラートを送信しない。
  </p>
  <p>
    介護する家族のメンバー——通常は成人した子供、配偶者、またはプロの介護者——は異なる経験を必要とする。彼らはより多くの情報を受け取ることをいとわず、家族のメンバーの健康について上昇した心配の状態を管理しているためにシステムを設定した可能性がある。この役割のために、アプリは夜間バイタルサインのサマリー、朝のレポートダイジェスト、そして睡眠者の設定から独立した設定可能なアラート設定を持つ専用の介護者ダッシュボードを提供する。
  </p>
  <p>
    高齢の親に対する共同責任が兄弟や大家族全体で文化的に期待されている日本やアジア全体で一般的な、多介護者家族では、システムは最大6人の指定された介護者をサポートし、それぞれが独立したアラート設定とエスカレーション設定を持つ。夜間シフトの介護者（通常は睡眠者と同居する親）は、音付きのTier 3アラートが有効になっているかもしれない。別の都市から確認している遠くにいる兄弟は、夜間アラートなしのサマリーのみの通知を持っているかもしれない。
  </p>

