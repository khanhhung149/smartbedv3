  <h2>SleepTechのアラートエンジンのアーキテクチャ</h2>
  <p>
    SleepTechのアラートシステムは、実際の生理的イベントに対する感度を損なうことなく偽陽性を減らすよう設計された、複数の層からなるメカニズムで構築されている。
  </p>
  <p>
    最初の層は<strong>60秒の測定ティック</strong>だ。生のセンサーデータから瞬時にバイタルサインを計算するのではなく、YumePadはローリング60秒ウィンドウで各メトリクスを処理する。これにより、寝返りや一時的な信号の欠損によって引き起こされる短時間のアーティファクトが、アラートを引き起こしうる孤立した異常データポイントを生成しない。60秒ウィンドウの平滑化効果により、ほとんどの過渡的なノイズがフィルタリングされ、真の生理的変化を表す持続的な逸脱は保存される。
  </p>
  <p>
    2番目の層は<strong>ベースラインのパーソナライゼーション</strong>だ。1日目、システムには個人的なコンテキストがない。年齢層別の規範データから導かれた保守的な集団ベースの閾値を適用する。最初の7〜14夜を通じて、システムは個人ベースラインを構築する：この個人の夜間各段階での正常な安静時心拍数の範囲は何か？通常の呼吸数の変動はどのようなものか？正常な動作パターンはどのようなものか？最初の2週間が終わる頃には、アラート閾値は個人に適応されており、自然に低い安静時心拍数（アスリートや高齢者によく見られる）が誤った高アラートを引き起こす可能性や、自然に動きの多い睡眠者が動作ベースの誤報を生成する可能性がはるかに低くなっている。
  </p>
  <p>
    3番目の層は<strong>Redisの重複排除ウィンドウ</strong>だ。異常なバイタルサイン読み取りが最初に検出されたとき、接続されている介護者にすぐにアラートを送信するのではなく、システムはモニタリング保留状態に入る。異常が設定された重複排除ウィンドウ内（ほとんどのバイタルサインタイプで通常3〜5分）に解決すれば、通知は送信されない。ウィンドウを超えて持続する場合、アラートはエスカレートする。この単一のメカニズムが、非接触睡眠モニタリングにおける偽陽性の最大のカテゴリーを排除する責任を担っている：数分以内に自然に解決する過渡的アーティファクト。
  </p>

