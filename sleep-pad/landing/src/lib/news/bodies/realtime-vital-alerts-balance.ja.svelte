  <p>
    午前2時47分、ベッドサイドテーブルの上のスマートフォンが静かな通知音を発する。ベッドの人が体を動かし、画面に目をやると、落ち着いたメッセージが表示されている。<em>「安静時心拍数が4分連続でわずかに上昇しています。監視中。」</em>3分後、2つ目のメッセージ：<em>「正常に戻りました。対応不要。」</em>眠っていた人は寝返りを打ち、再び眠りにつく。介護者は起こされなかった。救急車も呼ばれなかった。そして、本当のイベントも見落とされなかった。
  </p>
  <p>
    この一連の流れ——静かで、短く、自然に解決する——は、よく設計されたアラートシステムの理想を体現している。そして実際のところ、これを実現することは極めて難しい。医療モニタリングの歴史は、どちらかの方向に傾きすぎて失敗したシステムで溢れている。敏感すぎて、毎晩何十回もの誤報を発し続け、すべてのアラートが無視されるようになるもの。あるいは保守的すぎて、部屋にいる誰もが既に気づいているような出来事しか検知できないもの。SleepTechのエンジニアリングチームが2012年の大阪での創業以来取り組んできた設計課題は、世界中の睡眠医学研究者や臨床アラーム管理の専門家を悩ませてきた同じ問いだ：実際のイベントを確実に捉えながら、守るべき人々を疲弊させないアラートエンジンをどう構築するか？
  </p>

  <h2>夜間バイタルサインの生理学</h2>
  <p>
    効果的なアラートシステムを設計するには、まず「正常」がどのような状態かを理解する必要がある——そして睡眠中の正常は、多くの人が予想するよりもはるかに変動が大きい。睡眠中の心拍数は、睡眠段階を反映した特徴的なアーキテクチャを持っている。浅い睡眠（N1、N2）では、心拍数は覚醒時よりも控えめに低下し、短い覚醒や体位変換とともに変動する。深い徐波睡眠（N3）では、心拍数は夜間最低値に達し——健康な成人では覚醒時平均より10〜20拍低い——強い副交感神経緊張を特徴とする高いHRVを示す。REM睡眠中は、夢を見ている間の強烈な皮質活性化によって、心拍数が再び上昇し不規則になる。
  </p>
  <p>
    呼吸数も同様のパターンを示す。N3では遅く規則的で、REM中は速く変動が大きい。REM睡眠中の呼吸不規則性は夢を見る睡眠の正常な生理学的特徴だが、N3中の同じ不規則パターンは、閉塞性無呼吸エピソードのような重大なイベントを示す可能性がある。
  </p>
  <p>
    体動はさらに複雑な層を加える。夜間の短い体動の爆発——寝返り、姿勢変換、短い微小覚醒——は完全に正常であり、健康な睡眠者でも一晩に何十回も起こる。これらは非接触センサーで測定される心拍数と呼吸のシグナルを一時的に乱す。正常なバイタルサイン範囲からの逸脱を潜在的なイベントとして扱う単純なアラートシステムは、これらのアーティファクトで絶え間なく誤作動する。
  </p>

  <h2>アラート疲労が生命安全の問題である理由</h2>
  <p>
    臨床現場では、アラーム疲労は十分に記録されており、本当に危険な問題だ。ICUでの研究によれば、臨床アラームの発生率は患者一人あたり1日187件に達することがあり、その大部分は偽陽性か臨床的に無関係なものだ。このような量のアラームにさらされた看護スタッフは、予測可能な適応反応を示す：遅延した対応時間、アラームの消音、そして最終的には真の重大イベントがシフト中の100番目の不快なアラートと同じ緊急度で扱われるほどの脱感作。その結果は、有害な転帰とセンチネルイベントとして測定可能だ。
  </p>
  <p>
    在宅モニタリングの文脈では動態は異なるが、根本的な問題は同一だ。1夜に3回のアラートを受け取り、それが10分以内に介入なしに解決するという経験を2週間繰り返した介護者は、やがてそれらのアラートを眠り続けながらやり過ごすようになる。心理的なメカニズムは臨床現場と同じだ：神経系は一貫して対応不要なシグナルに慣化する。真の緊急事態がついに起きたとき、反応の遅れは致命的な長さになりうる。
  </p>
  <p>
    これは仮想の失敗モードではない。過度に感度の高いモニタリングシステムのすべてに共通する、予測可能な失敗モードだ。そしてこのことは、偽陽性の抑制を真陽性の検出と同じくらい重要なものとして扱う設計哲学を強く支持する。すべての実際のイベントを捉えるが、20件の誤報も生成するシステムは安全なシステムではない。無視されるよう訓練されているシステムだ。
  </p>

  <blockquote>
    <p>「最も危険なアラートは、発報しないアラートではない。それに先立つ50件の誤報によって消音されてしまったアラートだ。」</p>
    <footer>— 田中雪先生、大阪大学病院 睡眠医学・遠隔モニタリング</footer>
