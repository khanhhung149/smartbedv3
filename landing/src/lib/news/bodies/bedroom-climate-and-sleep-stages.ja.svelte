  <p>
    睡眠の質に影響を与えるすべての環境的要因の中で、寝室の温度は最も多くの人が理解していると思いながら、最も一貫して過小評価されているものだ。「快適であればいい」というのは合理的な直感だが、生物学が実際に必要とするものを見逃している。温度と睡眠の関係は従来の意味での快適さに関するものではない——体温調節に関するものであり、深い睡眠に入り維持するために身体が必要とする具体的な熱条件は、ほとんどの人が気づいているよりもずっと狭く正確に定義されている。
  </p>
  <p>
    徐波睡眠を開始するためには、深部体温が午後のピークから約1〜2°C低下しなければならない。これは睡眠開始の相関ではない——前提条件だ。深部体温と睡眠の概日タイミングの両方を調節する視床下部は、覚醒から睡眠への夜間の移行の一部としてこの温度低下を調整する。寝室の熱環境がこの深部体温の低下を妨げれば——部屋が暖かすぎるか、寝具の断熱性が高すぎるか、有効な蒸発冷却を可能にするには湿度が高すぎるか——その人がどれほど疲れていても、どれだけの時間ベッドで過ごしても、身体は完全には徐波睡眠に入れない。
  </p>
  <p>
    これは気候や季節を超えて実際的な含意を持つ具体的な生理学的事実だ。ほとんどの成人にとって最適な寝室温度範囲——約18〜20°C——は広く引用されているが、なぜ重要なのか、湿度がどのように温度と相互作用するか、これらの範囲が季節や年齢層によってどのようにシフトするか、そして環境を単純に理想的な値に設定できない場合に何ができるかの説明がほとんど伴っていない。
  </p>

  <h2>睡眠の体温調節アーキテクチャ</h2>
  <p>
    睡眠構造と体温調節は深く絡み合っている。それらがどのように相互作用するかを理解するには、身体が夜間を通じて熱的に何をしているかの簡単なレビューが必要だ。
  </p>
  <p>
    睡眠の数時間前、深部体温は午後後半のピーク（ほとんどの成人で通常37.2〜37.5°C）から低下し始める。この低下は眠りによって引き起こされるのではない——概日睡眠準備の一部として睡眠開始の1〜2時間前に始まる。そのメカニズムは末梢血管拡張を含む：手と足の血管が拡張し、温かい血液を核から末梢へ再分配し、そこで環境に熱を放射できる。これが温かい手と足が身体が睡眠を準備していることの信頼できるシグナルである理由だ。
  </p>
  <p>
    深部体温が低下し続けるにつれて、N3徐波睡眠に入る確率が急激に増加する。深い睡眠の遅い振動——N3を特徴づける大きく同期化した皮質波——は熱的にゲートされている：深部体温が夜間範囲の低い部分にあるときに最も容易に発生する。過度に温かい部屋、厚い寝具、遅い運動からの代謝熱、または発熱によって深部体温が上昇すると、N3睡眠は断片化し浅い段階に移行する。
  </p>
  <p>
    REM睡眠中、体温調節は一時停止される。視床下部はREM期間中、深部体温の積極的な調節を本質的に停止し、これがREM睡眠がNREM睡眠よりも極端な外気温に対してより敏感な理由だ。非常に寒いまたは非常に暖かい環境では、REM中の身体の体温調節ができないことがREM持続時間を短縮するか完全に断片化することがある。
  </p>

  <h2>温度と湿度：ほとんどのガイドが見逃す相互作用</h2>
  <p>
    温度だけでは熱環境の不完全な仕様だ。湿度は実質的に重要であり、特に季節によって大きく変動する気候——日本、ベトナム、タイ、東南アジアのほとんど——において重要だ。
  </p>
  <p>
    身体は睡眠中に主に三つのメカニズムで熱を失う：放射（皮膚表面から周囲の空気への熱放射）、対流（移動する空気によって運ばれる熱）、蒸発（皮膚表面からの水蒸気による熱損失）。中程度の温度では、放射と対流が支配的だ。しかし約24°C以上の温度——熱帯の夏の夜に一般的——では放射と対流の有効性が低下し、蒸発冷却がますます重要になる。
  </p>
  <p>
    蒸発冷却は皮膚表面の蒸気圧と外気湿度の差によって支配される。外気湿度が高い——相対湿度70%以上——と蒸気圧勾配が狭くなり汗の蒸発効率が低下する。身体は同じ冷却速度を維持するためにより多くの汗をかくが、より少ない成功しか収めない。結果として熱的不快感が生じ、不快感による睡眠の乱れ、そして深いN3睡眠への入りや維持を妨げる高い深部体温が生じる。
  </p>
  <p>
    睡眠に最適な湿度範囲——相対湿度40〜60%——はこの生理学に基づいている。40%以下では、空気が乾燥しすぎて睡眠中の呼吸で粘膜が乾燥し、喉の乾燥による夜間覚醒を引き起こす。これは高地や日本や北ヨーロッパの暖房環境のような乾燥した冬の気候で特に問題になる。60%以上では、22〜23°C以上の温度で深い睡眠の持続時間に測定可能な影響を与えるほど蒸発冷却効率が低下する。
  </p>

