  <h2>在宅技術ができないこと</h2>
  <p>
    在宅モニタリングの限界の誠実な表現は、その能力を伝えることと同様に重要だ。以下はすべてのユーザーと医療提供者が理解すべき本物の重要な制約だ。
  </p>
  <p>
    <strong>EEGなしでは睡眠段階分類ができない。</strong>非接触センサーからの睡眠段階分類は、脳電気活動の直接測定ではなく、間接的な代理——呼吸パターン、体動、心拍ダイナミクス——に依存する。これらのシグナルからのAI推定は広い分類（覚醒対NREM対REM）に対して合理的な精度を示しているが、より細かい段階境界を確実に検出したり、PSGが提供する詳細なEEGベースの分析を提供したりすることはできない。
  </p>
  <p>
    <strong>酸素飽和度測定ができない。</strong>パルスオキシメトリー——PSGの無呼吸特徴づけの中心となる血液酸素レベルの継続的測定——は皮膚に接触したセンサーを必要とする。非接触マットレス下センサーはSpO2を直接測定できない。無呼吸重症度分類と未治療無呼吸の心血管的影響に直接関連する酸素脱飽和イベントは、直接測定ではなく推定される。
  </p>
  <p>
    <strong>診断権限がない。</strong>在宅モニタリングデバイスはスクリーニングツールであり、診断機器ではない。YumePadの夜間レポートからの高確率の無呼吸シグナルは、臨床評価を求める強い理由——診断ではない。在宅モニタリングデータのみに基づいて、臨床的確認なしにCPAP療法を開始したり、口腔内装置を処方したり、外科的評価を計画したりすることは医学的に不適切だ。
