  <p>
    <strong>CSAはOSAより検出が困難だ。</strong>在宅デバイスが依存する動作と呼吸のシグネチャは、OSAに最も特徴的だ。特にCheynes-Stokes形態のCSAは、呼吸努力の周期性とクレッシェンド-デクレッシェンドパターンの分析を必要とする。在宅デバイスは純粋なCSAに対して感度が低く、疑われるCSAは在宅モニタリング結果にかかわらずPSGで評価されるべきだ。
