  <h2>睡眠時無呼吸とは何か：OSA、CSA、その間のスペクトラム</h2>
  <p>
    睡眠時無呼吸は単一の疾患ではない。睡眠中の呼吸の繰り返される中断——それぞれ少なくとも10秒間持続し、睡眠構造を断片化して生理学的影響をもたらすのに十分な頻度（無呼吸低呼吸指数、AHI）で発生する——を特徴とする関連疾患の集合体だ。
  </p>
  <p>
    <strong>閉塞性睡眠時無呼吸（OSA）</strong>は圧倒的に最も一般的な形態だ。睡眠中に上気道の筋肉——軟口蓋、口蓋垂、舌根部、咽頭壁——が弛緩し、気道が部分的または完全に閉塞する。脳の呼吸ドライブは呼吸するよう信号を送り続けるが、閉塞した通路では空気が動かない。酸素飽和度が低下し、数秒から1分後に脳が低酸素ストレスを感知して睡眠者を気道筋緊張を回復させるのに十分なほどに短く覚醒させる——睡眠者がほとんど意識的に記憶していないマイクロ覚醒だ。呼吸が再開し、しばしばあえぎや鼻いびきを伴う。このサイクルが一晩に何十回、時には何百回と繰り返される。
  </p>
  <p>
    <strong>中枢性睡眠時無呼吸（CSA）</strong>はより稀であり、メカニズム的に異なる。CSAでは気道は開通している——物理的な閉塞はない——しかし脳幹の呼吸制御センターが呼吸するよう信号を送ることに失敗する。呼吸筋はその指令を受けず、単純に収縮しない。呼吸の停止は通常OSAより静かであり（いびきやあえぎがない）、最も知られているCheynes-Stokes呼吸のような特徴的な周期的パターンで起こりうる。
  </p>
  <p>
    重症度はAHIで分類される：軽症（5〜14回/時）、中等症（15〜29回/時）、重症（30回/時以上）。AHI 15は、脳が一晩中少なくとも4分に1回は睡眠から短く覚醒していることを意味する。睡眠構造——特に回復に最も重要な深い徐波睡眠とREM睡眠——への累積的な影響は甚大だ。
  </p>

  <h2>未診断の無呼吸の規模</h2>
  <p>
    睡眠時無呼吸の有病率の疫学的推定は、使用されるAHI閾値と研究対象集団によってかなり異なる。大規模集団研究から最も広く引用される数字によれば、30〜70歳の男性の約17%、女性の約9%が中等症から重症のOSA（AHI ≥ 15）を有する。軽症例を含めると、一部の集団での有病率の推定は30%を超える。
  </p>
  <p>
    これは驚くべき数字だ。比較として、世界の成人集団における2型糖尿病の有病率は約10%だ。中等症から重症レベルの睡眠時無呼吸は2型糖尿病とほぼ同じくらい一般的——しかしその診断率は劇的に遅れている。臨床および保険データベースの研究では、OSAのAHIベースの診断基準を満たす個人のわずか10〜20%のみが正式に診断を受け、治療を受けていることが一貫して示されている。
  </p>
  <p>
    未診断・未治療の中等症から重症OSAの健康上の影響は実質的で十分に確立されている。無呼吸のない個人と比べて、未治療の中等症から重症OSAを持つ人は高血圧のリスクが約2倍、新規2型糖尿病のリスクが2〜3倍、心筋梗塞や脳卒中を含む心血管イベントのリスクが2〜4倍高く、日中の眠気による交通事故率も著しく高い。
  </p>

