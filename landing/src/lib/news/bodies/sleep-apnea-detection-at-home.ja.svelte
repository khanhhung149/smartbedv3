  <h2>ポリソムノグラフィーに対する利点</h2>
  <p>
    実験室でのポリソムノグラフィー（PSG）は睡眠時無呼吸診断のリファレンス標準であり続ける。これはEEG（睡眠段階分類のための脳電気活動）、EOG（REM検出のための眼球運動）、EMG（覚醒と四肢運動のための筋電図）、ECG、サーミスタと圧力変換器による鼻腔気流、胸部および腹部呼吸努力バンド、パルスオキシメトリー、体位、マイクロフォン録音を同時に記録する。
  </p>
  <p>
    このデータ密度は、睡眠技術者と医師が夜間のすべてのイベントを正確に特徴づけることを可能にする。この包括性にもかかわらず、PSGには集団レベルのスクリーニングに対する重大な実際的制限がある。在宅ベースのモニタリングはこれらのいくつかに直接対処している。
  </p>
  <p>
