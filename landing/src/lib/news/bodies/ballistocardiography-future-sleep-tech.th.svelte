  <h2>ประวัติย่อ: จากกอร์ดอนถึงการค้นพบใหม่</h2>
  <p>
    ประวัติของ BCG เป็นเรื่องราวของการค้นพบใหม่ การสังเกตของกอร์ดอนในปี 1877 ได้รับการบันทึกแต่ไม่ได้รับการพัฒนาอย่างเป็นระบบ อุปกรณ์ของ Starr ในปี 1939 มีความซับซ้อนในยุคนั้นแต่ต้องการเงื่อนไขที่ป้องกันการนำไปใช้ทางคลินิก ตลอดทศวรรษที่ 1940 และ 1950 BCG สร้างผลงานวิจัยจำนวนมากที่เชื่อมโยงพารามิเตอร์รูปคลื่น BCG กับผลผลิตของหัวใจ การทำงานของลิ้นหัวใจ และโรคหลอดเลือดหัวใจ
  </p>
  <p>
    เทคนิคนี้เสื่อมความนิยมในทศวรรษที่ 1960 และ 1970 เมื่อ echocardiography และ nuclear cardiology ปรากฏขึ้นเป็นเครื่องมือที่ทรงพลังกว่าสำหรับการประเมินหัวใจ BCG ดูเหมือนจะเป็นความอยากรู้อยากเห็นทางประวัติศาสตร์ เทคโนโลยีได้เข้าสู่การหยุดพักประมาณ 30 ปี
  </p>
  <p>
    การฟื้นฟูเริ่มขึ้นในช่วงต้นทศวรรษ 2000 ขับเคลื่อนในตอนแรกโดยกลุ่มวิชาการที่สนใจการติดตามสัญญาณชีพที่ไม่รบกวนสำหรับการดูแลผู้สูงอายุ บทความสำคัญมาจากกลุ่มที่ MIT, Georgia Tech และมหาวิทยาลัยญี่ปุ่นหลายแห่งรวมถึงโอซากา ซึ่งความต้องการในการติดตามประชากรที่แก่ชราในบ้านโดยไม่มีภาระการปฏิบัติตามของอุปกรณ์สวมใส่ได้สร้างแรงจูงใจที่แข็งแกร่งในการทำให้ BCG ทำงานได้ในบ้านจริงบนเตียงจริง
  </p>
  <p>
    ทีมผู้ก่อตั้ง SleepTech ในโอซากาในปี 2012 รวมถึงนักวิจัยที่ทำงานเกี่ยวกับการประมวลผลสัญญาณ BCG สำหรับการติดตามผู้สูงอายุตั้งแต่กลางทศวรรษ 2000 การเปลี่ยนผ่านจากโปรแกรมวิจัยทางวิชาการไปสู่ผลิตภัณฑ์สำหรับผู้บริโภคต้องแก้ปัญหาทางวิศวกรรมที่แตกต่างกันสามประการ: การย่อขนาดเซ็นเซอร์ให้บางเท่ากับแผ่นที่นอน การพัฒนาโมเดล ML ที่แข็งแกร่งต่อเสียงรบกวนในโลกจริง และการสร้างไปป์ไลน์การคำนวณเพื่อรันการอนุมานด้วยอัตราที่จำเป็นบนฮาร์ดแวร์ฝังตัวกำลังไฟต่ำ
  </p>

