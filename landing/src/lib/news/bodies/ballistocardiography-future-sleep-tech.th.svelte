  <h2>BCG vs PPG vs ECG: การเปรียบเทียบสัญญาณ</h2>
  <p>
    การทำความเข้าใจตำแหน่งของ BCG ในความสัมพันธ์กับโมดัลลิตี้การตรวจจับหัวใจหลักอื่นๆ ช่วยชี้แจงว่า BCG ทำได้ดีที่ไหนและมีข้อจำกัดที่ใด
  </p>
  <p>
    <strong>ECG (คลื่นไฟฟ้าหัวใจ)</strong> วัดกิจกรรมไฟฟ้าของหัวใจโดยตรวจจับความต่างศักย์ไฟฟ้าทั่วผิวร่างกาย R-wave ของ ECG ให้จังหวะหัวใจที่แม่นยำมากช่วยให้วัดช่วง R-R ด้วยความแม่นยำต่ำกว่ามิลลิวินาที ECG เป็นมาตรฐานทองคำสำหรับการตรวจจับ arrhythmia การวิเคราะห์การนำกระแสไฟฟ้าหัวใจ และการวัด HRV ข้อจำกัดสำหรับการตรวจสอบการนอนหลับแวดล้อมคือต้องการการสัมผัสขั้วไฟฟ้าที่ผิวหนัง
  </p>
  <p>
    <strong>PPG (Photoplethysmography)</strong> วัดการเปลี่ยนแปลงปริมาตรของการไหลเวียนเลือดโดยตรวจจับว่าเนื้อเยื่อดูดซับแสงมากแค่ไหนเมื่อเลือดผ่าน LED บนหลังนาฬิกาอัจฉริยะเป็นเซ็นเซอร์ PPG มีความสะดวก แต่นำเวลาหน่วงเทียบกับเหตุการณ์ไฟฟ้าหัวใจ มีความแม่นยำที่แปรเปลี่ยนขึ้นกับการไหลเวียนเลือดส่วนปลายและอาร์ติแฟกต์การเคลื่อนไหว และต้องสัมผัสร่างกาย
  </p>
  <p>
    <strong>BCG</strong> วัดแรงกลที่เกิดจากการพ่นเลือดของหัวใจตามที่ถ่ายทอดผ่านร่างกายไปยังพื้นผิวรองรับ ไม่ต้องการการสัมผัสร่างกาย ความสัมพันธ์เวลากับวัฏจักรหัวใจนั้นซับซ้อนกว่า ECG แต่คุณสมบัติทางสถิติของลำดับช่วงเวลาระหว่างการเต้น (ซึ่งเป็นสิ่งที่การวิเคราะห์ HRV ใช้) ได้รับการรักษาดีพอสำหรับการวิเคราะห์บริบทการนอนหลับ
  </p>
  <p>
    <strong>ข้อได้เปรียบหลักของ BCG</strong> ไม่ใช่ว่ามันเหนือกว่า ECG หรือ PPG ในคุณภาพสัญญาณดิบ แต่เป็นการที่มันทำงานโดยไม่ต้องสัมผัสร่างกาย ทำให้เป็นโมดัลลิตี้เดียวที่สามารถบรรลุการปฏิบัติตามการวัดกลางคืน 100% โดยไม่มีข้อกำหนดพฤติกรรมจากผู้ใช้
  </p>

  <h2>การประมวลผลสัญญาณ BCG สมัยใหม่: AI สกัดสุขภาพจากการสั่นสะเทือนอย่างไร</h2>
  <p>
    สัญญาณ BCG ที่จับโดยเซ็นเซอร์ใต้ที่นอนจริงไม่ดูเหมือนรูปคลื่นที่สะอาดในตำราเรียน มันเป็นการซ้อนทับของสัญญาณหัวใจที่ต้องการกับแหล่งเสียงรบกวนหลายแหล่ง: การเคลื่อนไหวจากการหายใจ (ครอบงำเนื้อหาความถี่ต่ำ) การเปลี่ยนท่า (อาร์ติแฟกต์ step-function ที่ใหญ่กว่าสัญญาณหัวใจหลายเท่า) การเคลื่อนไหวของคู่นอน และการสั่นสะเทือนสิ่งแวดล้อมจากการจราจรและระบบ HVAC
  </p>
  <p>
    ไปป์ไลน์การประมวลผล BCG สมัยใหม่จัดการสิ่งนี้เป็นชั้นๆ: <strong>adaptive bandpass filtering</strong> แยกแถบความถี่ที่มีเนื้อหาหัวใจ BCG (ประมาณ 1-15 Hz) ขณะปฏิเสธการเคลื่อนไหวจากการหายใจ (~0.5 Hz ด้านล่าง) และเสียงรบกวนความถี่สูง <strong>การตรวจจับการเปลี่ยนท่า</strong> ระบุอาร์ติแฟกต์แอมพลิจูดสูงที่เกี่ยวข้องกับการจัดตำแหน่งร่างกายใหม่และปิดกั้นหน้าต่างเหล่านี้จากการวิเคราะห์หัวใจ <strong>การหลอมรวมหลายเซ็นเซอร์</strong>ในการกำหนดค่าแบบ dual-zone ใช้การแยกระยะห่างเชิงพื้นที่ระหว่างเซ็นเซอร์เพื่อแยกแยะระหว่างสองผู้ใช้ในเตียงร่วมกัน <strong>การตรวจจับพีคและการประมาณช่วงเวลาระหว่างการเต้น</strong> ใช้การจับคู่เทมเพลตและการจำแนกพีคแบบ ML เพื่อระบุคลื่น J ในสัญญาณที่ทำความสะอาดแล้ว <strong>การจำแนกระยะการนอนหลับ</strong> รวมคุณลักษณะจังหวะหัวใจ คุณลักษณะอัตราการหายใจและความลึก และคุณลักษณะการเคลื่อนไหวร่างกายในโมเดลเวลา (โดยทั่วไปคือสถาปัตยกรรม LSTM หรือ Transformer) ที่จัดแต่ละ epoch 30 วินาทีเป็น ตื่น N1 N2 N3 หรือ REM
  </p>

