  <p>
    เทคโนโลยีภายใน YumePad สืบทอดสายเลือดทางปัญญามาถึงแพทย์ชาวสก็อตชื่ออเล็กซานเดอร์ กอร์ดอน ในปี 1877 ซึ่งเป็นคนแรกที่บันทึกการสังเกตว่าร่างกายกระเด็นเล็กน้อยกับทุกการเต้นของหัวใจ ปรากฏการณ์ที่เขาสังเกตในผู้ป่วยที่นิ่งพอที่จะสังเกตเห็น Isaac Starr ที่มหาวิทยาลัยเพนซิลเวเนียในปี 1939 สร้างอุปกรณ์พิเศษที่ติดบนโต๊ะเพื่อวัดการเคลื่อนไหวขนาดเล็กเหล่านี้อย่างเป็นระบบและบัญญัติคำว่า "ballistocardiograph" ในทศวรรษต่อมา BCG มีบทบาทที่กระตือรือร้นแต่ยังเป็นชายขอบในหัวใจวิทยาทางคลินิก แล้วก็มาถึงการผสมผสานของเซ็นเซอร์ MEMS การประมวลผล edge และการเรียนรู้ของเครื่อง และหลักการวัดที่พัฒนาในยุคตะเกียงแก๊สก็กลายเป็นเครื่องยนต์ของเทคโนโลยีการติดตามหัวใจแบบต่อเนื่องที่เข้าถึงได้มากที่สุดในโลก
  </p>

  <h2>ฟิสิกส์ของ BCG: สิ่งที่ร่างกายบอกที่นอน</h2>
  <p>
    หลักการทางกลที่เป็นพื้นฐานของ BCG นั้นตรงไปตรงมา ทุกครั้งที่หัวใจหดตัวและส่งเลือดเข้าสู่หลอดเลือดแดงใหญ่ กฎข้อที่สามของนิวตันจะใช้บังคับ: การพ่นเลือดออกแรงกระทำต่อเลือด และเลือดก็ออกแรงตอบสนองเท่ากันและตรงข้ามต่อร่างกาย แรงตอบสนองนี้ที่เรียกว่า ballistic force มีขนาดเล็ก (ระดับมิลลินิวตันสำหรับปริมาณ stroke ของหัวใจทั่วไป) แต่สามารถวัดได้หากอุปกรณ์วัดมีความไวเพียงพอและต่อกันกับร่างกายทางกล
  </p>
  <p>
    ในอุปกรณ์ดั้งเดิมของ Starr ผู้ป่วยนอนบนโต๊ะที่แขวนอยู่อย่างอิสระซึ่งสามารถเคลื่อนที่ในแนวนอนด้วยแรงเสียดทานต่ำ การเคลื่อนที่ของโต๊ะกับแต่ละการเต้นของหัวใจถูกวัดโดย transducer รูปคลื่นที่ได้ซึ่งก็คือ BCG มีรูปร่างที่เป็นลักษณะเฉพาะ: ชุดของคลื่นที่ระบุว่า I, J, K, L, M, N ซึ่งสอดคล้องกับเฟสที่แตกต่างกันของวัฏจักรกลไกของหัวใจ คลื่น J ซึ่งเป็นการเบี่ยงเบนบวกที่ใหญ่ที่สุด สอดคล้องกับจุดสูงสุดของการพ่นของหัวใจ คลื่น K เป็นการเบี่ยงเบนลบที่เกี่ยวข้องกับการชะลอตัวของการไหลของเลือดเมื่อพบกับความต้านทานของหลอดเลือด
  </p>
  <p>
    เซ็นเซอร์ BCG สมัยใหม่ไม่ต้องการแพลตฟอร์มที่แขวนอย่างอิสระ ฟิล์ม piezoelectric, strain gauge และเซ็นเซอร์แรง capacitive สามารถตรวจจับแรงกลขนาดเล็กที่ถ่ายทอดผ่านที่นอนด้วยความไวเพียงพอสำหรับการดึงสัญญาณระดับคลินิก ความท้าทายได้เปลี่ยนจากฟิสิกส์ไปสู่การประมวลผลสัญญาณ: การแยกสัญญาณ BCG ออกจากอาร์ติแฟกต์การเคลื่อนไหวจากการหายใจ การเคลื่อนไหวของคู่นอน และพื้นสัญญาณรบกวนสิ่งแวดล้อมในสภาพแวดล้อมบ้านจริง
  </p>

