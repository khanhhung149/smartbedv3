  <h3>アンカー睡眠</h3>
  <p>
    アンカー睡眠戦略——すべてのシフトタイプにわたって重複する固定のコア睡眠期間を維持すること——は、ローテーションシフト労働者のための最も実用的な概日安定化技術の一つだ。原則は簡単だ：シフトスケジュールに関係なく一貫して保てる4〜5時間の睡眠ウィンドウを選ぶ（例えば、日夜交代勤務の労働者には午前3時〜7時）。このアンカー期間は常に守られる。シフトに応じて、その前後に追加睡眠が加えられる。概日システムはコア睡眠のタイミングによってフェーズ設定されるため、このアンカーを維持することで、時計がローテーション間に行わなければならない総フェーズシフトが減少し、再整列時間とそれに伴う健康への影響が減少する。
  </p>

  <h3>戦略的光療法</h3>
  <p>
    光は主要な概日同期装置であり、その意図的な使用は夜勤への適応を加速させることができる。概日研究でよく確立されたプロトコルは、夜勤の最初の部分での明るい光暴露（2,500〜10,000ルクス、専用の光療法ランプまたは屋外光から）と、帰宅通勤中（青波長光をブロックする黒いサングラスを通じて）および日中の睡眠中の厳格な光回避を含む。この明暗プロトコルは、介入なしの1日あたり1時間未満と比較して、理想的な条件下で1日あたり最大2時間の概日フェーズシフトができる。
  </p>

