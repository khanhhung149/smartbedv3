  <h3>遮光環境と睡眠スケジュール</h3>
  <p>
    夜勤労働者の昼間の睡眠環境は、夜間の睡眠条件をできるだけ近似する必要がある。完全遮光カーテン（「薄暗くする」カーテンではなく、縁からの光漏れのない真の遮光）が最も重要な単一の環境変更だ。寝室温度は17〜20℃に積極的に冷やす必要がある。昼間の周囲温度は夜間温度より通常高く、深い睡眠開始に必要な深部体温の降下を妨げる。
  </p>
  <p>
    ホワイトノイズまたは耳栓が音響環境に対処する：宅配、交通、家庭内活動、子供たちによる昼間の騒音レベルは夜間よりも実質的に高く、日中に眠るシフト労働者の睡眠は、集団研究では夜間睡眠の約2倍の音響的障害によって断片化される。
  </p>

