  <p>
    3回連続の夜勤を終えた看護師。3週間サイクルで日勤、準夜勤、夜勤を交代でこなす工場労働者。6つのタイムゾーンを越えて2日後に戻ってくる航空機パイロット。まったく予測可能なリズムのないスケジュールをこなす救急科医師。これらは例外的なケースではない——先進国の労働人口の推定20%が従来の午前7時〜午後6時の枠外でシフト勤務を行っており、その多くにとって、健康へのコストは重大であり、大部分が見えず、大部分が対処されていない。
  </p>
  <p>
    シフト勤務は概日リズムを、曝露年数とともに蓄積する形で乱す。研究は明確だ：長期のシフト労働者は、心血管疾患、代謝症候群、2型糖尿病、うつ病、消化器疾患、および特定のがんの発生率が高い。生物学的メカニズムは謎ではない——概日システムは睡眠だけでなく、体のほぼすべての生理プロセスを支配しており、内部時計と外部の明暗サイクルとの持続的なずれは、細胞レベルで健康を劣化させる。
  </p>

  <h2>概日リズムのずれの生物学</h2>
  <p>
    人間の概日システムは、視床下部の視交叉上核（SCN）にあるマスターペースメーカーによって固定されており、網膜からの直接入力を通じて明暗サイクルに同期する。このマスター時計は、ホルモンシグナルと神経出力のカスケードを通じて、すべての臓器——肝臓、心臓、腸、副腎、免疫細胞——の末梢時計を同期させる。日勤労働者が夜勤に移行するときのように、明暗暴露パターンが劇的かつ突然に変化すると、末梢時計は再整列するのに数日から数週間かかり、しかも異なる速度で行う：肝臓は副腎とは異なるペースで適応し、腸は心臓とは異なるペースで適応する。この内部非同期——同じ体の中の時計が異なるスケジュールで動いている——は、外部非同期と同様に有害であり、1週間以内に再整列する時差ボケの旅行者と慢性シフト労働者を区別するものだ。
  </p>
  <p>
    主要な概日同期シグナルであるメラトニンは、生物学的な日中は光によって抑制され、生物学的な夜の暗闇の中で上昇する。日中に眠る夜勤労働者にとって、日光——締め切ったカーテン越しでも——は継続的な抑制シグナルを提供し、昼間の睡眠時間を短縮し、その構造を悪化させる。複数の研究が一貫して、夜勤後の昼間の睡眠は、同じ個人の夜間睡眠より短く（通常1〜2時間少ない）、浅く（徐波睡眠が少ない）、断片化していることを示している。
  </p>

  <h2>実践的な戦略：エビデンスが支持するもの</h2>
  <p>
