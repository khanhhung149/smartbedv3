  <h2>これらの物語に共通するもの</h2>
  <p>
    三つの家族、三か国、三つの全く異なる介護のコンテキスト。共通するのは、同じ根本的な問題のバリエーションです：見守りが必要な人を、ケアする人がリスクが最も高い時間帯に立ち会えないという現実。そして従来の対応策——毎日の電話、チェックインアプリ、定期訪問、専門介護者——はすべて同じ構造的限界を持っていました：情報を間欠的に提供するものであって、継続的にではない。
  </p>
  <p>
    継続的な受動的モニタリングが変えるのは、ケアそのものではありません——電話は続き、訪問は続き、人間関係はケアの中心にあり続けます。変わるのは、そのケアの情報的な基盤です。介護者——東京の娘であれ、ハノイの息子であれ、バンコクのケアコーディネーターであれ——は、夜間に愛する人がどのような状態にあるかについて、継続的で客観的で生理的に根拠のある記録にアクセスできます。
