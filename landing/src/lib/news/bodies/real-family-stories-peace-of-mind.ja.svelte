  <h2>物語その一：恵子と北海道のお母さん</h2>
  <p>
    恵子は47歳、東京のテクノロジー企業でプロダクトマネージャーを務めています。母親の文子は81歳で、恵子が育った札幌の実家に一人で暮らしています。二人の間の距離は道路で831キロ、飛行機で約90分——恵子が年に4〜5回、連休や母の体調が心配なときに越える距離です。その合間には電話があります。過去11年間、ほぼ例外なく毎晩午後7時に。
  </p>
  <p>
    恵子にとって、この電話はつながりであり負担でもありました。「私が電話しないと母が心配するとわかっていたので、一度も欠かしたことがありません。出張中でも、ぐったり疲れていても、電話しました。そして電話では母はいつも元気だと言う。でも、元気かどうかにかかわらず、『元気』と言うんだなとわかってきました。私を心配させないように守ってくれているんです。」電話は母の声を届けてくれましたが、声の裏にある情報は届けてくれませんでした。
  </p>
  <p>
    文子は2年前に一度転倒したことがあります——深刻なものではなく、打撲と、ひどく怖がった娘でしたが——その転倒が恵子に特定の夜間不安を残しました。どんな安心できる会話でも完全には拭えない不安を。「時々夜中の3時に目が覚めて、ただ横になってこう考えるんです：トイレに立ったかな？転んだかな？今、床の上に倒れていて、7時に電話するまで私にはわからないんじゃないか？」想像したシナリオ——母が床に倒れて電話に手が届かず、時間が過ぎていく——は不合理ではありませんでした。一度ほぼそうなりかけたことがあったのです。
  </p>
  <p>
    YumePadは春の訪問中に設置されました。文子が設定やアラートしきい値の選択に完全に参加して。文子の最初の反応——「じゃあ、私がトイレに行くたびにわかるの？」——には、アラートが何を表示して何を表示しないかについての丁寧な説明で答えました。その会話が何かを変えました。「母は『まあ、それであなたが眠れるなら構わないわ』と言いました。その言葉が今も心に残っています。母はすでに自分の眠りではなく私の眠りのことを考えていたのです。」
  </p>
  <p>
    最初の2週間、恵子は毎朝起き上がる前に強迫的にアプリを確認していました。4週目には、習慣が定まりました：朝の概要を短くチェックし（コーヒーの後、前ではなく）、夕方の電話をします。「電話が変わりました。以前は常に彼女の声の中に何か悪いものを探していました。今は、母が『よく眠れたわ』と言うと、その意味が実際にわかります。見えるからです。私のための演技じゃない。」
  </p>
  <p>
    設置から8か月後、文子の睡眠概要に恵子が見たことのないパターンが現れました：睡眠中の安静時心拍が大幅に上昇した2夜続きと、早朝の異常に長いベッド退出イベント。3日目の朝、午後7時の電話の前に、恵子は午前9時に母に電話しました。文子は言っていませんでしたが、息切れがしていたのです。その日の午後に医師を受診しました。診断は軽度の心房不整脈——薬で管理できますが、速やかな治療が必要でした。「アプリが診断したわけじゃない」と恵子は言います。「でも、母が何も言わないと決める前に電話する理由を与えてくれた。」
  </p>

  <blockquote>
    <p>「今でも毎晩電話します。これからもずっとそうします。でも今は電話が違う——ただの愛であって、偵察ではない。」</p>
    <footer>— 恵子、47歳、東京（複合事例研究）</footer>
