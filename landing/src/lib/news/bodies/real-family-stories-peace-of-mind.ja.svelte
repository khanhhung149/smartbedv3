  <h2>物語その二：ミンとフエのお父さん</h2>
  <p>
    ミンは39歳、ハノイの半導体メーカーでエンジニアとして働いています。父親のトゥアンさんは73歳で、ベトナム中部の古都フエの実家に暮らしています——ミンが22歳でホーチミン市に勉強のために去り、以来住んでいない街です。トゥアン氏は14か月前に軽度の虚血性脳卒中を発症しましたが、ほぼ完全な機能回復を遂げています。しかし、その出来事は家族に、再発に対する持続的で根拠のある不安を残しました。
  </p>
  <p>
    ミンの家族を悩ませていたのは、午後10時から午前6時の時間帯でした：トゥアン氏が寝室で一人でいる時間、家族の誰も血管イベントの初期兆候を認識できる立場にいない時間。ミンの母は4年前に亡くなっています。妹はフエの2時間南のダナンに住んでいます。近所の退職者のBác Hùngが毎晩様子を見に来ます。しかし、夜は別の問題です。
  </p>
  <p>
    YumePadはリモートで設置されました——ミンがビデオ通話で父親に設置手順を説明し、物理的な配置にはBác Hùngが協力しました。一度稼働すると、アラートシステムは脳卒中後のモニタリング専用に設定されました：安静時心拍上昇アラート（確立されたベースラインの20%上昇でトリガー設定）、ベッド退出時間アラート（閾値：30分）、そして毎朝の概要をミンと妹に共有。
  </p>
  <p>
    4か月目に異なるパターンが現れました。5夜にわたって、トゥアン氏の睡眠中の安静時心拍がベースライン平均の61BPMから74、78、ついには83BPMへと徐々に上昇しました。5日目の朝、ミンは父親が起きる前に電話し、妹に連絡して、その日の午後フエへ向かってもらいました。トゥアン氏は熱を出していました——かかりつけ医が簡単に治療できる呼吸器感染でしたが、抗凝固療法を受けている脳卒中後の患者としては、速やかな受診が必要なリスクがありました。感染は数日前から進行していました。トゥアン氏は子どもたちを心配させたくなかったのです。
  </p>
  <p>
    「父は文句を言わない世代です」とミンは言います。「何かが深刻になるまで待って、その頃には最善の対応のための時間が過ぎているかもしれない。センサーは、彼が自分では教えてくれない情報を与えてくれます。隠しているのではなく——本当に迷惑をかけたくないから。データは彼が何を言うことにしたかにかかわらず、彼の体が何をしているかを教えてくれます。」
  </p>
  <p>
    ミンの家族に残ったフレーズは、その年のテトの夕食で妹が使ったものです：「Ba có hai gia đình bây giờ」——お父さんには今、二つの家族がある。生物学的な家族と、夜間に静かに見守るデジタルの家族と。
  </p>

  <h2>物語その三：バンコクの介護コレクティブ</h2>
  <p>
    三番目の肖像は性格が異なります：生物学的家族ではなく、専門的なケアアレンジメント。ノンはバンコクで小さな高齢者ケアコーディネーションサービスを運営しています——居住施設ではなく、サートーンとシーロム地区の各自宅に住む12名の高齢クライアントのネットワーク。ノンの組織と契約を結んだ家族のために、週一回の確認、薬の管理、医療機関への送迎、緊急対応コーディネーションを担います。
  </p>
  <p>
    ノンはこの仕事を9年間続けています。クライアントにYumePadとスマートベッドシステムを導入する前の夜の体験を、分散した人口を対象にケアを管理したことがある人なら誰でも即座に共感できる言葉で説明します：「毎晩、スマートフォンを最大音量にして、枕のそばに置いて眠っていました。普通は何も問題なかったから——普通は何も問題がない——でも、誰かが教えてくれるまで、何か問題があるかどうかわかりませんでした。そして誰かが教えてくれる頃には、最善の対応のための時間が過ぎているかもしれない。」
  </p>
  <p>
    12名のクライアントにセンサーモニタリングを導入する決断は単純ではありませんでした。各クライアントに同意とデータ共有について個別に話し合う必要がありました。12名のうち9名が設置に同意しました。1名はプライバシーの懸念を理由に断り、2名は「考えてみる」と言いました（両者とも後に、友人の家でシステムを見て同意しました）。
  </p>
  <p>
    ノンは自分自身の睡眠の変化を、システム導入の最初で最も直ちに気づく結果として説明します。「最初の週は、習慣で午前3時に目が覚めていました。3週目には朝まで眠れるようになっていました。ケアをやめたからではなく——自分が個人的に提供できない時間帯のケアをシステムに委ねて、何か注意が必要なことがあればシステムが起こしてくれると信頼できたから。」
  </p>

