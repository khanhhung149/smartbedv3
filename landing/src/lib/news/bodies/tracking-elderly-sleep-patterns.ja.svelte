  <h2>医療上の問題を示す可能性のある微妙な変化</h2>
  <p>
    上述した基準となる変化は正常だが、高齢者の特定の睡眠変化は臨床的な注意を要する。難しいのは、これらの変化がしばしば微妙で、徐々に発展し、高齢者自身が報告する症状を生じさせないことが多いという点だ——比較の基準がない、変化を「ただの老化」と思っている、あるいは根底にある状態が症状を認識して報告するのに必要な認知的明晰さに影響を与えているためだ。
  </p>
  <p>
    <strong>尿路感染症（UTI）</strong>——特に女性の高齢者——は非典型的な症状を呈することが多い。若い患者に典型的な排尿痛や頻尿ではなく、高齢者のUTIはしばしば主として急性の混乱、行動変化、睡眠障害として現れる。夜間の目覚めの急増、特に介護者から見える行動変化を伴う場合は、他の症状が現れる前のUTIの早期サインである可能性がある。高齢者のUTIは未治療のまま放置すると、危険な速さで敗血症に進行することがあるため、行動的・睡眠パターンモニタリングによる早期発見は真の臨床的緊急性を持つ。
  </p>
  <p>
    <strong>認知症</strong>、特にアルツハイマー病は、場合によっては認知症状より何年も前に現れる特徴的な睡眠構造の変化をもたらす。研究は睡眠障害とアミロイド蓄積の双方向関係を確立している：睡眠障害は脳からアミロイドベータを除去するグリンファティック清掃を妨げ、一方で睡眠調節を司る領域でのアミロイド蓄積がさらに睡眠を障害する。初期認知症に関連する睡眠変化には、睡眠断片化の増加、REM睡眠行動障害（RBD——夢の内容を身体的に演じること、パーキンソン病やレビー小体型認知症を含むシヌクレイノパチーの強力な予測因子）、および正常な概日睡眠覚醒パターンの漸進的な障害が含まれる。
  </p>
  <p>
    高齢者の<strong>うつ病</strong>は認識と治療が不十分なことが多く、その睡眠シグネチャーは特徴的だ：早朝覚醒（予定より何時間も早く目覚め、眠れない）、徐波睡眠の減少、異常に早い最初のREM発症、持続的な疲労を伴う総睡眠時間の減少。このパターンは正常な老化による睡眠変化から区別可能であり、2〜4週間持続する場合は臨床評価が正当化される。
  </p>

  <h2>家族が注意すべきこと</h2>
  <p>
    高齢の親族を介護する家族——同居でも遠距離でも——のために、以下の行動パターンは注意を要し、医師へのコミュニケーションが必要だ：
  </p>
  <ul>
    <li><strong>夜間行動の急激な変化：</strong>夜間の目覚めの突然の増加、興奮、異常な時間帯のベッドからの離床、または目覚め時の混乱（睡眠惰性の通常の軽い混乱とは異なる）は、その人の確立された基準からの変化である場合に特に、速やかな対応を要するシグナルだ。</li>
    <li><strong>数週間にわたる進行性の睡眠断片化：</strong>明らかな環境的説明なしに、2〜4週間にわたる夜間覚醒回数の徐々に増加することは、医療的、心理的、または神経学的変化の発展を示す可能性がある。</li>
    <li><strong>REM睡眠行動の指標：</strong>高齢者が睡眠中に動作、発声、または夢を「演じている」ように見えるという（睡眠空間を共にするパートナーや介護者からの）報告は、臨床的に重要な知見であり、記録して神経科医と議論すべきだ。</li>
    <li><strong>早朝覚醒パターン：</strong>通常の時間より2時間以上早く、一貫して目覚め、眠れない——特に低い気分、意欲の欠如、または認知的なもやを伴う場合——は晩年のうつ病の評価を促すべきだ。</li>
    <li><strong>日中の睡眠行動の変化：</strong>夜間の睡眠に支障を与えるほどの昼寝の増加、または逆に定期的に昼寝していた高齢者が完全に昼寝をやめることは、どちらも調査の価値がある睡眠構造の変化を反映する可能性がある。</li>
  </ul>

