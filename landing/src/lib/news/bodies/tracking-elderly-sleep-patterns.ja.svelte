    睡眠は加齢とともに変化する。これは睡眠医学において最も一貫して、かつ最もよく記録された知見の一つだ——そして、高齢者自身にも、彼らを心配する家族にも、最も頻繁に誤解されることの多い知見でもある。75歳の人に見られる不眠や断片的な睡眠は、加齢に伴う正常な睡眠構造の表れかもしれない。「浅い眠り」としか見えないものが、臨床的な注意を要する何かの早期警告かもしれない。この違いは、家族がどう対応するか、医師がどう助言するか、そして睡眠テクノロジーがこの集団をどう支援するよう設計されるかに、とてつもなく重要な意味を持つ。
  </p>
  <p>
    この記事では、加齢がいかに睡眠を内側から再形成するか——この変化を駆動する神経学的、ホルモン的、概日リズム的変化——そして、YumePadによる継続的な非接触睡眠モニタリングが、家族と臨床医が予期されることと懸念すべきことを区別するのにどう役立つかを探る。
  </p>

  <h2>加齢が睡眠構造に与える影響</h2>
  <p>
    加齢に関連した睡眠の最も重要な変化は、徐波睡眠（N3、深い睡眠またはデルタ睡眠とも呼ばれる）の漸進的な減少だ。若い成人では、N3は通常、総睡眠時間の15〜20%を占める。70代になると、この割合はしばしば一桁になり、場合によっては5%未満になることもある。この変化の背後にある生理学的メカニズムは、複数の相互作用する要因を含む：成長ホルモン（N3エポックと一致するパルスで放出される）の分泌減少、脳波で測定されるデルタ波振幅と出力の低下、そして加齢とともによりゆっくり蓄積する恒常的な睡眠欲求の変化——覚醒中に蓄積する深眠圧力が低くなることを意味する。
  </p>
  <p>
    REM睡眠はそれほど劇的には影響を受けないが、変化を示す：REM期は夜の早い時間に起こり、より短く、若い成人のREMを特徴づける鮮明な皮質活性化が少なくなる。REM睡眠の割合は老年期まで概ね維持されるが、晩年のREMは若年のものとは構造的に異なる。
  </p>
  <p>
    浅い睡眠段階（N1とN2）がN3が空けた割合を埋めるように拡大する。実際的な結果として、高齢の眠り手はより容易に覚醒しやすい浅い段階で夜の多くを過ごす。これにより短時間の覚醒が増える——その多くは意識的に記憶されない——そして「浅い眠り」や「本当に眠れていない」という主観的な経験に寄与する。
  </p>
  <p>
    睡眠効率——ベッドにいる時間のうち実際に眠っている時間の割合——は加齢とともに低下する。睡眠効率92〜95%の若い成人は典型的だ。75〜80%の効率の高齢者は年齢に対して全くの正常かもしれない。この区別は重要だ：若い成人の睡眠効率基準を高齢者に適用すると、誤解を招く結果と不必要な不安を生む。
  </p>

  <h2>概日リズムのシフト：早寝早起き</h2>
  <p>
    加齢は概日フェーズの前進をもたらす——生物時計が早まる。これは極端な場合に進行性睡眠相障害と呼ばれることもあるが、正常な形では単に「睡眠相前進」と呼ばれる。高齢者は自然に夕方早く眠気を感じ、朝早く目を覚ます。このシフトに逆らおうとすること——午後10時の就寝が「早すぎる気がする」からといって深夜まで起きていること——は、概日フェーズに逆らって誘発された睡眠をもたらし、生物時計に合わせた睡眠よりも質が低く、断片化が多い。
  </p>
  <p>
    概日リズムのシフトには、高齢の親族と同居する家族に実際的な影響がある。午後9時に就寝し午前5時に起床する85歳の人は病的な状態を発症したわけではない。彼らは自分の生物学によって決定されたスケジュールで眠っている。課題は家族のスケジュールが衝突するときに生じる——高齢者の固まった睡眠期間中に家がうるさくなる場合や、「皆と同じように」夜更かしすることへの社会的圧力が睡眠を断片化させる場合だ。
  </p>
