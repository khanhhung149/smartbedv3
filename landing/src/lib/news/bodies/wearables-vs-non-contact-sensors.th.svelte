  <h2>ความแม่นยำ: จุดแข็งและจุดอ่อนของแต่ละหมวดหมู่</h2>
  <p>
    ทั้งสองหมวดหมู่ได้รับการตรวจสอบความถูกต้องทางวิชาการอย่างอิสระกับ PSG (polysomnography) มาตรฐานทองคำของห้องปฏิบัติการ สรุปที่ซื่อสัตย์ของสถานะการวิจัยปัจจุบัน:
  </p>
  <p>
    <strong>เวลานอนหลับรวม (TST):</strong> ทั้งเซ็นเซอร์สวมใส่และไร้สัมผัสทำงานได้ดีพอสมควรในการประมาณ TST ในผู้นอนปกติ โดยทั่วไปอยู่ในช่วง 10-15% ของการประมาณ PSG อุปกรณ์สวมใส่มีแนวโน้มประมาณ TST สูงเกินไปในผู้นอนหลับไม่ดี (ถือว่าการตื่นเงียบๆ เป็นการนอนเบา) ในขณะที่เซ็นเซอร์ BCG อาจประมาณ TST ต่ำเกินไปในผู้นอนที่นิ่งมาก
  </p>
  <p>
    <strong>การจำแนกระยะการนอนหลับ:</strong> Oura Ring แสดงความแม่นยำของอุปกรณ์สวมใส่ที่ดีที่สุด โดยบางการศึกษาตรวจสอบความถูกต้องแสดงให้เห็นความสอดคล้องแบบ epoch-by-epoch กับ PSG ประมาณ 75-78% สำหรับการจำแนก 4 ระยะ Apple Watch และ Whoop อยู่ในช่วง 68-74% ระบบที่ใช้ BCG รวมถึง YumePad แสดงความแม่นยำ 4 ระยะที่เทียบเคียงหรือต่ำกว่าเล็กน้อย (65-75%) ในการตรวจสอบอิสระ โดยข้อจำกัดหลักคือการตรวจจับ N1
  </p>
  <p>
    <strong>การวัด HRV:</strong> นี่คือที่การเปรียบเทียบมีความละเอียดอ่อนมากขึ้น การวัด HRV ด้วย PPG ที่ข้อมือมีความเสี่ยงต่ออาร์ติแฟกต์จากการเคลื่อนไหวที่เพิ่มขึ้นในท่านอนต่างๆ PPG แบบแหวน (Oura) ทำงานได้ดีกว่าเนื่องจากการลดลงของการผสมกับการเคลื่อนไหวและความใกล้ชิดกับหลอดเลือดที่ดีกว่า HRV ที่ได้จาก BCG ของ YumePad บรรลุความแม่นยำที่เทียบเคียงกับ Oura Ring ในการศึกษาตรวจสอบที่ควบคุม
  </p>
  <p>
    <strong>การตรวจจับเหตุการณ์การหายใจ:</strong> ระบบ BCG มีข้อได้เปรียบที่มีนัยสำคัญที่นี่ การหายใจปรับรูปแบบ BCG ในแบบที่ช่วยให้โมเดล ML ที่ฝึกมาสามารถประมาณอัตราการหายใจ ตรวจจับรูปแบบการหายใจแบบวัฏจักร และตั้งค่าสถานะดัชนีเหตุการณ์การหายใจ (REI) ที่อาจเกี่ยวข้องกับความผิดปกติของการหายใจขณะนอนหลับได้
  </p>

  <h2>สมการความสะดวกสบายและการปฏิบัติตาม</h2>
  <p>
    ข้อกำหนดความแม่นยำมีความสำคัญน้อยกว่าที่เห็นหากอุปกรณ์ไม่ได้ถูกสวมใส่อย่างสม่ำเสมอ นี่คือความจริงที่น่าไม่สบายใจเกี่ยวกับการเปรียบเทียบความแม่นยำของเครื่องติดตามการนอน: ความแม่นยำในโลกจริงระยะยาวของอุปกรณ์คือผลคูณของความแม่นยำทางเทคนิคและอัตราการปฏิบัติตาม อุปกรณ์ที่มีความแม่นยำ 80% แต่สวมใส่ 60% ของคืนสร้างข้อมูลตามแนวยาวที่แย่กว่าอุปกรณ์ที่มีความแม่นยำ 72% แต่สวมใส่ 97% ของคืน
  </p>
  <p>
    <strong>อุปสรรคการปฏิบัติตามของอุปกรณ์สวมใส่</strong> รวมถึง: ความถี่ในการชาร์จ (Apple Watch ทุกคืน; Whoop และ Oura ประมาณสัปดาห์ละครั้ง) เวลาชาร์จ (การชาร์จระหว่างหน้าต่างการนอนขัดจังหวะชุดข้อมูล) ความไม่สะดวกสบายทางกายภาพระหว่างการนอน (รอยกด ความร้อน การรับรู้ถึงอุปกรณ์) และการลืมหรือหลีกเลี่ยงโดยเจตนาในคืน "แย่" ซึ่งเป็นช่วงที่ข้อมูลจะน่าสนใจทางคลินิกมากที่สุด
  </p>
  <p>
    <strong>ความกังวลเกี่ยวกับการสัมผัสผิวหนังระยะยาว</strong> ควรกล่าวถึงโดยเฉพาะ แม้ว่าจะไม่มีความเสี่ยงต่อสุขภาพเฉียบพลันสำหรับเซ็นเซอร์ PPG สวมใส่สำหรับผู้บริโภค แต่สัดส่วนเล็กน้อยแต่มีนัยสำคัญของผู้ใช้รายงานผิวหนังอักเสบจากการสัมผัส รอยกด และการระคายเคืองผิวหนังจากการสวมใส่ต่อเนื่อง บุคคลบางรายยังรายงานการรบกวนการนอนจากการรับรู้การสวมใส่อุปกรณ์
  </p>
  <p>
    <strong>การปฏิบัติตามของเซ็นเซอร์ไร้สัมผัส</strong> แตกต่างกันอย่างมีโครงสร้าง เมื่อวางไว้ใต้ที่นอนแล้ว ไม่มีอะไรให้จำ ไม่มีอะไรให้ชาร์จ ไม่มีอะไรให้ทนทาน การปฏิบัติตามเป็น 100% โดยพื้นฐานตราบใดที่ผู้ใช้นอนบนเตียงที่ติดตาม นี่คือข้อได้เปรียบที่ทรงพลังที่สุดสำหรับการติดตามตามแนวยาว
  </p>

