    高齢者ケアの危機の中に、もうひとつの健康危機が埋め込まれています。それが受けるべき注目のほんの一部しか受けていない問題——介護者自身の危機です。24時間体制で高齢者のケアを担う何百万もの家族や専門職者は、自分自身の身体的・精神的健康、人間関係、キャリアを犠牲にしながら介護を続けています。この隠れた疾病の中心にある、特定の、そしてほぼ認識されていない害の形があります。それは、介護者の睡眠を組織的に破壊することです。
