  <h2>介護者が目覚める理由：不安な警戒ループ</h2>
  <p>
    家族介護者が夜間にこれほど頻繁に目を覚ます理由を理解するには、二つの異なる要因を区別する必要があります：正当な医療ニーズと不安な警戒。
  </p>
  <p>
    正当な医療ニーズは、夜間の覚醒の一部を説明します。一部の要介護者は本当に夜間の身体的補助を必要とします：床ずれを防ぐための体位変換、薬の服用、夜間失禁の管理、または本物の苦痛への対応。しかし研究から研究へと、家族介護者の夜間覚醒の大部分は別の何かによって引き起こされています：不安な警戒。介護者が目を覚ますのは、要介護者が呼んだり必要性を示したりしたからではなく、要介護者が大丈夫だという安心なしには眠れないからです。
  </p>
  <p>
    この不安な警戒ループは自己強化的であり、合理的な介入に対して抵抗します。介護者に「もっと睡眠を取るべき」と伝えることは、物理的に確認せずに要介護者が安全かどうかを知ることができないために睡眠が妨げられているなら有用なアドバイスではありません。知識のギャップ——物理的に確認せずに、隣の部屋の人が大丈夫かどうかを知ることができないこと——が、睡眠を破壊する警戒の根本原因です。
  </p>

