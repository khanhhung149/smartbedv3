  <h2>介護者の睡眠剥奪の生物学</h2>
  <p>
    睡眠分断——頻繁な覚醒による連続した睡眠の中断——は、単純に睡眠時間が減ることとは生理的に異なります。連続して6時間眠った人は、4回の中断を伴って8時間眠った人よりも休息感を感じることがよくあります。これは、最も回復をもたらす睡眠段階——特に徐波睡眠（N3）と夜の後半の統合されたREM周期——が発達するためには、継続的で中断のない睡眠が必要だからです。
  </p>
  <p>
    夜に3〜5回目を覚ます家族介護者にとって、慢性的な睡眠分断の累積効果は予測可能な経路で現れます。研究文献は記録しています：介護者における高血圧リスクの23%増加；慢性的なストレス反応と一致した炎症マーカー（IL-6、CRP）の上昇；代謝症候群に先行するグルコース調節の障害；テロメア長で測定された細胞の老化加速——介護者は、マッチした非介護のコントロールと比較して、約6年分の生物学的老化の加速に相当するテロメアの短縮を示しています。これは自己犠牲の生物学です。
  </p>
  <p>
    認知的な結果も同様に重大であり、より即座に目に見えます。睡眠不足は、実行機能、作業記憶、感情調節、複雑な意思決定の能力を損ないます。これらはまさに介護が要求する認知能力です。慢性的に睡眠不足の介護者は、薬のスケジュールの複雑さを管理する能力が低下し、要介護者の状態の変化に柔軟に対応する能力が低下します。
  </p>

