  <h2>ภูมิทัศน์ของภัยคุกคาม: อะไรที่อาจเกิดขึ้นได้ผิดพลาด</h2>
  <p>
    การทำความเข้าใจภัยคุกคามความเป็นส่วนตัวเฉพาะต่อข้อมูลการนอนหลับช่วยกำหนดกรอบว่าทำไมทางเลือกทางวิศวกรรมจึงสำคัญ
  </p>
  <p>
    <strong>การขายให้นายหน้าข้อมูล</strong> แอปสุขภาพและสุขภาวะสำหรับผู้บริโภคมีประวัติที่มีเอกสารรองรับดีในการขายหรือแบ่งปันข้อมูลผู้ใช้กับนายหน้าข้อมูล ซึ่งเป็นบริษัทที่โมเดลธุรกิจคือการรวมและขายต่อโปรไฟล์ข้อมูลส่วนบุคคล การสอบสวนปี 2020 โดย British Medical Journal พบว่า 19 จาก 24 แอปสุขภาพยอดนิยมแบ่งปันข้อมูลกับบุคคลที่สาม รวมถึงเครือข่ายโฆษณาและนายหน้าข้อมูล มักโดยไม่มีความตระหนักรู้ของผู้ใช้
  </p>
  <p>
    <strong>การละเมิดข้อมูล</strong> ข้อมูลสุขภาพเป็นหนึ่งในหมวดหมู่ข้อมูลที่มีค่าที่สุดในตลาดมืด บันทึกการดูแลสุขภาพขายได้สูงกว่าหมายเลขบัตรเครดิตหลายเท่า เพราะข้อมูลสุขภาพสามารถใช้สำหรับการฉ้อโกงประกันภัย การฉ้อโกงยาตามใบสั่งแพทย์ และการโจมตีทางวิศวกรรมสังคมเป้าหมาย
  </p>
  <p>
    <strong>การเลือกปฏิบัติด้านประกันภัย</strong> ในเขตอำนาจศาลที่ไม่มีการคุ้มครองการไม่เลือกปฏิบัติทางพันธุกรรมที่เข้มแข็ง ข้อมูลสุขภาพที่ได้จากอุปกรณ์ผู้บริโภคถูกใช้ในการตัดสินใจรับประกันภัย ตัวบ่งชี้ความผิดปกติของการนอนหลับ เช่น ดัชนีเหตุการณ์การหายใจที่บ่งชี้ภาวะหยุดหายใจขณะนอน หรือรูปแบบ HRV ที่เกี่ยวข้องกับความเสี่ยงหัวใจ อาจส่งผลต่อเบี้ยประกันภัยหรือการตัดสินใจความคุ้มครองหากผู้รับประกันภัยสามารถเข้าถึงได้
  </p>
  <p>
    <strong>การเข้าถึงของเจ้าหน้าที่ตำรวจ</strong> ข้อมูลสุขภาพดิจิทัลที่เก็บไว้บนเซิร์ฟเวอร์ของบริษัทอยู่ภายใต้กระบวนการทางกฎหมาย เช่น หมายเรียก คำสั่งศาล คำขอของเจ้าหน้าที่ ในเขตอำนาจศาลที่เซิร์ฟเวอร์เหล่านั้นตั้งอยู่
  </p>

