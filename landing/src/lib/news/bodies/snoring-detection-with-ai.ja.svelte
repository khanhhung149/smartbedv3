  </p>

  <h2>いびきの真の原因</h2>
  <p>
    いびきは、呼吸中の乱流によって上気道の軟部組織——軟口蓋、口蓋垂、扁桃弓、舌根部、咽頭壁——が振動することで生じる。眠りにつくと、喉を開いた状態に保つ筋肉が弛緩する。この弛緩が一定の閾値を超えると、気道が狭くなる。狭い管を通る空気の流れは速くなり乱流が生まれ、周囲の組織が振動する。これがいびきの音の源だ。
  </p>
  <p>
    いくつかの解剖学的・生理学的要因がいびきのリスクを高める。生来の狭い咽頭構造、肥大した扁桃腺やアデノイド、鼻閉や鼻中隔弯曲（これにより口呼吸が強制され咽頭筋が弛緩する）、アルコール摂取（さらに咽頭筋緊張を低下させる）、首周りの過剰な脂肪などだ。体位も重要な要素であり、仰臥位で眠ると重力によって舌と軟口蓋が後方に落ち込み、側臥位よりも気道が狭くなる。
  </p>
  <p>
    現代の睡眠医学が強調する重要な洞察は、いびきが一様な現象ではないということだ。健康上の影響を持たない良性の一次性いびきから、軽度の上気道抵抗を伴う習慣性いびき、そして閉塞性睡眠時無呼吸（OSA）の徴候としてのいびきまで、スペクトルが存在する。どの位置に当てはまるかは、音だけから常に判断できるわけではない——そこにAI搭載の音響分析が状況を変える。
  </p>

  <h2>重要なシグナル：音響、体動、呼吸</h2>
  <p>
    睡眠モニタリングシステムがいびきを意味ある形で特徴づけるためには、単なる音の有無以上のものを捉える必要がある。3つのシグナルモダリティを組み合わせることで、完全な像が浮かび上がる。
  </p>
  <p>
    <strong>音響シグナル</strong>が一次的ないびき特徴づけを提供する。いびきのスペクトル包絡——周波数全体にわたるエネルギーの分布——は、閉塞が発生する気道の場所によって再現可能な形で異なる。軟口蓋に起因するいびきは、エネルギーが低周波数帯に集中し、比較的規則的な波形を持つ傾向がある。舌根部や下咽頭レベルのより深い気道に起因するいびきは、より不規則で広帯域のスペクトルを持ち、しばしば音量も大きい傾向がある。いびき音の特定のスペクトル的・時間的特徴は、無呼吸の重症度の予測に使えることが研究で示されており、接触センサーなしで音響的ないびき分析だけからでもAHI（無呼吸低呼吸指数）を意味ある精度で推定できる。
  </p>
  <p>
    <strong>体動シグナル</strong>が重要な第二層を追加する。睡眠時無呼吸中、各無呼吸イベントに続く短い覚醒——気道緊張を回復させ呼吸を再開させる覚醒——は、BCGセンサーで検出可能な特徴的な体動パターンを生じさせる。覚醒の微小体動は通常、小さく突発的で、その後体位変換が続く。高品質なマットレス下センサーは、秒単位の時間分解能でこれらのイベントを検出できる。音響的ないびきイベントが体動覚醒と時間的に相関する場合、システムはいずれかのシグナル単独よりも、臨床的に有意な無呼吸の証拠をより強く持つことになる。
  </p>
  <p>
    同じBCGセンサーからの<strong>呼吸パターンシグナル</strong>が全体像を完成させる。真の閉塞性無呼吸は10秒以上の気流停止を生じさせるが、特徴的なパターンは、呼吸努力が継続する——胸部と腹部は閉塞した気道に対して呼吸を試み続ける——一方で、オーディオマイクロフォンは沈黙を検出し、その後気道が再開したときに大きないびき音の爆発を検出するというものだ。このパターン——流れのない努力、そして突然の再開——は睡眠医学において最も臨床的に重要なシグネチャーの一つであり、今やマットレスベースのモニタリングプラットフォームから検出可能だ。
  </p>

