  <p>
    11秒に1人——これが、アメリカで転倒に関連した負傷により救急治療室に搬送される高齢者の頻度です。19分に1人が命を落とします。これらは、稀な事故や特別なリスク状況から生まれた統計ではありません。多くの事例が夜間に起こり、見慣れた自宅の中で、何十億もの人々が何も考えずに行う行動——トイレに行くためにベッドから起き上がる——の最中に発生しています。65歳以上の高齢者にとって、その何気ない動作は、医学が最近ようやく体系的に取り組み始めた最も重大なリスクの瞬間のひとつとなっています。
  </p>
  <p>
    夜間の転倒がなぜこれほど危険なのかを理解するには、午前2時、3時、4時に高齢者がベッドから立ち上がろうとする瞬間に、どのような要素が重なり合うかを理解する必要があります。血圧はサーカディアンリズムの最低点にあり、臥位から立位への移行時に起こる立ちくらみ（起立性低血圧）は、一日のほかのどの時間帯よりも顕著です。睡眠から目覚めた直後は筋肉の協調性が低下しています。判断力も鈍ります。照明は最小限です。そして、膀胱が満たされた切迫感が、慎重さよりも速さへの衝動をかき立てます。これが、高齢者の転倒の多くが実際に起きる生理的な文脈です。
  </p>

  <h2>公衆衛生上の危機としての転倒：数字で読む実態</h2>
  <p>
    転倒は、データが入手可能なすべての高所得国において、65歳以上の成人における致死・非致死的損傷の最大原因です。SleepTechが拠点を置く日本では、転倒が65歳以上の傷害関連入院の約30%を占め、高齢化と単身・少人数世帯での生活が進む中で、その数は着実に増加しています。
  </p>
  <p>
    骨折や頭部外傷といった直接的な負傷は、臨床的な連鎖の始まりにすぎません。75歳以上で股関節骨折を経験した高齢者の1年死亡率は、研究によって15〜30%に及び、多くの生存者が恒久的な移動能力と自立の喪失を経験します。骨折を伴わない転倒でさえ深刻な影響をもたらします。「転倒恐怖症」は、最初の転倒や転倒しそうになった経験が、その後の移動への持続的な不安を生み、自発的な活動制限につながる——これ自体が機能低下、社会的孤立、さらなる転倒の主要リスク因子となる——という記録された現象です。
  </p>
  <p>
    夜間が特に危険なのは、バイオメカニクスだけの問題ではなく、発見の遅れにあります。昼間、家族がいる自宅で起きた転倒なら数秒〜数分で対応できます。しかし、午前3時に高齢者が一人で暮らす寝室で起きた転倒は、数時間気づかれないことがあります。同じ股関節骨折であっても、20分で救急車が到着した場合と、6時間床に倒れたままの場合では、死亡率、恒久入院の確率、自宅に戻れる確率がまったく異なります。
  </p>

