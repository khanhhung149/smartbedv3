  <h2>床在知検出とは何か</h2>
  <p>
    床在知検出（ベッドプレゼンス検出）は、睡眠モニタリングに使われるのと同じマットレス下センサー技術の特定用途です。睡眠モニタリングが心拍数・呼吸・動きを追って睡眠ステージを推定するのに対し、床在知検出はより単純かつ二択の問いに集中します——今この瞬間、ベッドに人がいるかどうか。
  </p>
  <p>
    マットレス下に設置されたYumePadセンサーは、人が寝ているベッドに対応する圧力分布と微細動作信号を継続的に測定します。これらの信号が消えた時——圧力が消え、呼吸や寝返りに対応する特徴的な微振動シグネチャが途絶えた時——システムはベッド退出イベントを記録します。タイムスタンプ、退出の持続時間、そのパターン（どれほど素早く起き上がったか、どれほどの時間ベッドを離れているか）がログに残り、家族アラート設定がある場合は指定した家族のスマートフォンに送信されます。
  </p>
  <p>
    このテクノロジーは、意図的・定型的な退出（人がゆっくり起き上がり、方向を変え、ベッドを離れるパターンは、転倒や異常に素早い退出を示す急激な不在とは異なる）と異常事態を区別します。通常のトイレ時間を超えた長時間の不在——家族が設定可能な閾値で、通常は15〜30分——が優先アラートを発動します。通常の時間内にベッドに戻った場合は、静かな確認としてログに残りますが、家族が特に要求しない限りアラートは発生しません。
  </p>
  <p>
    最も重要なのは、高齢者が何かを装着したり操作したりする必要が一切ないことです。付け忘れる心配のあるリストバンドも、混乱した瞬間に手を伸ばすパニックボタンも、調整やメンテナンスが必要なカメラもありません。監視はただそこにある——常に動作し、決して負担を与えず、高齢者が実際に生活している現実を尊重するかたちで。
  </p>

  <h2>アラートの連鎖：検出から対応へ</h2>
  <p>
    検出は最初のステップにすぎません。ベッド退出が記録された瞬間から、家族や介護者が対応できる状態になるまでに何が起きるか——それが、テクノロジーが実際に結果を変えるかどうかを左右します。SleepTechのアラート設計に対するアプローチは、夜間アラートシステムの行動的現実に関する長年の研究を反映しています。
  </p>
  <p>
    核心的な課題は、エンジニアが感度-特異度トレードオフと呼ぶものです。すべての退出でアラートを出すシステムは、ほとんどの退出が定型的で無害なものであることから、家族にアラートを無視する習慣をつけさせてしまいます。一方、アラートを出すまでの待機が長すぎると、防ごうとしていた事態そのものを招きかねません。SleepTechのアラートロジックは段階的アプローチを採用しています——すぐに解決した退出には短い猶予期間でアラートなし、通常の時間を超えたが閾値に達していない退出にはソフト通知、そして懸念の閾値を満たした退出には——特有の音響・振動パターンを持つ——優先アラート。
  </p>
  <p>
    SleepTechのファミリーアプリの優先アラートは、エスカレーションチェーンで設定できます。まず第1連絡者に通知が届き、一定時間（通常3〜5分）内に確認されなければ第2連絡者へとエスカレートします。どちらも対応しない場合は、第3の連絡者——近所の人、プロの介護者、または家族が最後の手段として設定した連絡先——に通知されます。この連鎖は、アラートが消音されたスマートフォンの中で消えないことを保証します。
  </p>

  <h2>スマートベッドの角度調整との統合</h2>
  <p>
    床在知検出は、アクティブな介入——特にスマートベッドの角度調整機能——と統合されると、大幅に力を増します。YumePadセンサーと並行して開発されたSleepTechのスマートベッドプラットフォームには、ベッド退出イベントに自動で応答するようプログラムできる電動ヘッド・フット角度調整システムが含まれています。
  </p>
  <p>
    具体的な介入は、前述の起立性低血圧リスクを標的にしています。YumePadがベッド退出の前に通常見られる早期動作シグネチャを検出した時——端に向かう体重移動、マットレス遠端の圧力低下、姿勢関連の微振動の変化——スマートベッドは積極的にヘッド部分を持ち上げ、ベッドフレームのフットボード内蔵のナイトライティングシステムを起動できます。この緩やかな傾斜は、水平から垂直への移行速度を落とし、人が完全に立ち上がる前に姿勢調整のための15〜30秒を提供します。自動点灯は、最も急激な見当識障害が起きる暗闇の瞬間をなくします。
  </p>
  <p>
    34名の高齢参加者を対象にした、YumePadとスマートベッドを統合したシステムを使った6か月のパイロット研究では、「懸念される退出」（異常に素早い出発と長時間の不在）に分類されたイベントの頻度が、ベースライン監視期間と比較して44%減少しました。この減少は、自動ベッド応答による行動安定化の直接的効果と、家族の意識向上という二次的効果（アラートをきっかけにした家族間の会話が、いくつかの参加者の自宅における安全改善——絨毯の除去、手すりの設置——につながった）の両方に起因すると考えられています。
  </p>

