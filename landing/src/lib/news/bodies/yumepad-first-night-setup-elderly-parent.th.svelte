  <h2>การจับคู่ Bluetooth ผ่านแอป</h2>
  <p>
    ดาวน์โหลดแอป SleepTech บนอุปกรณ์ที่จะทำหน้าที่เป็นอุปกรณ์หลักที่จับคู่ — โดยปกติคือสมาร์ทโฟนของพ่อแม่ถ้ามี หรือสมาร์ทโฟนของคุณถ้าการตั้งค่าจะถูกจัดการโดยครอบครัวเป็นหลัก เปิดแอปและแตะ "เพิ่มอุปกรณ์ใหม่" แอปจะนำทางคุณผ่านการจับคู่ Bluetooth กับฮับ กระบวนการใช้เวลาประมาณ 90 วินาทีและไม่ต้องมีความรู้ทางเทคนิค
  </p>
  <p>
    เมื่อจับคู่แล้ว แอปจะถามให้ยืนยันด้านการนอน ว่าพ่อแม่ของคุณนอนในเตียงที่ใช้ร่วมกัน (ในกรณีนี้ ระบุว่าพวกเขาอยู่ด้านไหนของเตียง) หรือนอนคนเดียว สำหรับการตั้งค่าเตียงที่ใช้ร่วมกัน สามารถเพิ่ม YumePad ที่สองสำหรับคู่ชีวิตได้
  </p>

  <h2>การตั้งค่าการเชิญครอบครัว</h2>
  <p>
    การเชิญครอบครัวเป็นคุณสมบัติที่เปลี่ยน YumePad จากเครื่องติดตามการนอนหลับส่วนตัวเป็นเครื่องมือดูแล จากเมนูหลักของแอป พ่อแม่ของคุณไปที่การตั้งค่า → การแบ่งปันครอบครัว → เชิญสมาชิกครอบครัว ป้อนอีเมลของคุณ คุณได้รับลิงก์เชิญ ยอมรับ และจากนั้นคุณจะได้รับสรุปรายคืนที่พ่อแม่ของคุณเลือกที่จะแบ่งปัน
  </p>
  <p>
    การไหลของการเชิญถูกออกแบบให้เริ่มต้นโดยผู้สูงอายุโดยเจตนา ไม่ใช่โดยสมาชิกครอบครัว นี่ไม่ใช่ข้อจำกัดทางเทคนิค แต่เป็นการเลือกโดยเจตนาที่สะท้อนถึงหลักการกำกับดูแลข้อมูลของ SleepTech ผู้สูงอายุคือเจ้าของข้อมูล พวกเขาเชิญคุณเข้ามา พวกเขาสามารถเพิกถอนการเข้าถึงได้ตลอดเวลา
  </p>

  <h2>ช่วงการเรียนรู้ค่าพื้นฐาน: 3 ถึง 7 คืน</h2>
  <p>
    สิ่งสำคัญที่สุดที่ต้องเข้าใจเกี่ยวกับสัปดาห์แรกกับ YumePad คือระบบกำลังเรียนรู้ บุคคลแต่ละคนมีสรีรวิทยาการนอนหลับที่เป็นเอกลักษณ์ — รูปแบบอัตราการเต้นของหัวใจที่เฉพาะตัวในช่วงการนอนหลับต่างๆ ความแปรปรวนของอัตราการหายใจที่เป็นเอกลักษณ์ เวลานอนหลับและตื่นนอนตามนิสัย รูปแบบการเคลื่อนไหวปกติในตอนกลางคืน YumePad สร้างโมเดลค่าพื้นฐานส่วนบุคคลจากข้อมูลคืนแรก 7 คืน และค่าพื้นฐานนี้คือสิ่งที่ทำให้การตรวจจับความผิดปกติในภายหลังมีความหมาย
  </p>
  <p>
    ในช่วงการเรียนรู้นี้ ข้อมูลที่แอปแสดงถูกต้อง แต่คุณสมบัติการตรวจจับความผิดปกติและการวิเคราะห์แนวโน้มถูกปิดใช้งานหรือมีการระบุชัดเจนว่า "ค่าพื้นฐานไม่เพียงพอ" ช่วงค่าพื้นฐานขั้นต่ำที่เชื่อถือได้คือสามคืนสำหรับโมเดลการจัดระยะการนอนหลับขั้นพื้นฐาน และเจ็ดคืนสำหรับโมเดลการตรวจจับความผิดปกติเต็มรูปแบบ
  </p>

