  <h2>การติดตั้งทางกายภาพ: ใต้ที่นอน ไม่ใช่ใต้แผ่นรอง</h2>
  <p>
    YumePad ติดตั้งได้ในเวลาไม่ถึงห้านาที แผ่นเซ็นเซอร์ — ประมาณ 60 ซม. × 40 ซม. ขนาดใกล้เคียงหมอนเล็ก — สอดใต้ที่นอน โดยศูนย์กลางอยู่ใต้บริเวณการนอนของลำตัวพ่อแม่ของคุณ แผ่นควรวางระหว่างที่นอนและฐานเตียง (หรือ box spring, แผ่น, หรือโครงแพลตฟอร์ม) ไม่ใช่ระหว่างที่นอนและผ้าปูที่นอน เซ็นเซอร์ต้องการน้ำหนักของที่นอนอยู่เหนือเพื่อตรวจจับการสั่นสะเทือนระดับไมโครของการเต้นของหัวใจและการหายใจ
  </p>
  <p>
    ตำแหน่งมีความสำคัญ โซนเซ็นเซอร์ของ YumePad อยู่ที่ส่วนกลางบนสามในหนึ่งส่วนของแผ่น ควรวางไว้ใต้ที่หน้าอกและท้องส่วนบนของพ่อแม่จะวางเมื่อนอนในท่าปกติ ถ้าพ่อแม่มีแนวโน้มนอนตรงกลางเตียง ให้จัดวางแผ่นให้อยู่ตรงกลางตามนั้น ถ้าพวกเขามักนอนชิดด้านใดด้านหนึ่ง ให้เลื่อนแผ่นเพื่อให้โซนเซ็นเซอร์อยู่ใต้ตำแหน่งการนอน
  </p>
  <p>
    แผ่นเชื่อมต่อกับหน่วยฮับขนาดเล็ก — ใกล้เคียงขนาดกล่องไม้ขีดใหญ่ — ผ่านสายบางที่วิ่งตามด้านข้างเตียง ฮับเสียบเข้ากับเต้าเสียบมาตรฐานและเชื่อมต่อผ่าน Bluetooth ไฟ LED สีเขียวดวงเดียวบนฮับยืนยันว่าเซ็นเซอร์กำลังรับสัญญาณ ถ้า LED กะพริบสีอำพัน แผ่นไม่ได้ตรวจจับสัญญาณเพียงพอ — โดยปกติเพราะต้องจัดตำแหน่งใหม่ให้ใกล้กับศูนย์กลางของโซนการนอนมากขึ้นเล็กน้อย หรือเพราะที่นอนหนาหรือหนาแน่นผิดปกติ
  </p>

