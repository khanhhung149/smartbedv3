    <p>"ฉันคิดว่ามันจะทำให้ลูกชายมาวุ่นวายมากขึ้น แต่กลับทำให้เขาวุ่นวายน้อยลง เขาเห็นได้ว่าฉันสบายดี เขาก็หยุดจินตนาการว่าฉันไม่สบาย"</p>
