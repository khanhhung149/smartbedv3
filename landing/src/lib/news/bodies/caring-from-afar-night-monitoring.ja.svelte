  <h2>ケーススタディ：由紀と静岡の母</h2>
  <p>
    田中由紀は44歳、大阪の製造会社でプロジェクトマネージャーを務める。母の文子は81歳で、由紀が育った静岡の家に一人で住んでいる——新幹線で2時間半の距離だ。文子は年齢の割に体は丈夫で、頭もしっかりして、自立しており、介護施設への入居や定期的なホームヘルパーの受け入れという考えにも強く抵抗している。「転んだほうがまし」と由紀は半ば冗談めかして言ったことがある。
  </p>
  <p>
    心配が始まったのは3年前、文子が夜間に短い混乱状態になったときだ——トイレに起きて、暗い廊下で方向感覚を失い、ベッドに戻れるようになるまで40分間床に座っていた。転倒はなく、骨も折れていなかった。しかし、文子が由紀にそのことを話したのは1週間後で、ほとんど話の途中だった。「もし転んでいたら？一晩中そこに座っていたら？」由紀は、その考えが今ずっと頭の片隅に住むようになったと表現した。
  </p>
  <p>
    YumePadの設置は由紀の提案で、睡眠健康モニターとして明示的にフレーミングされた——雑誌でHRVと深い睡眠について読んで、母が自分の睡眠を理解することに興味を持つかもしれないと思った。文子は由紀が予想していた以上に熱心に同意した。「彼女は、私が見ているためではなく、自分の健康のためだという考えが気に入ったと思います」と由紀は説明した。
