  <h2>日本の高齢化社会：問題の規模</h2>
  <p>
    日本の人口動態状況は、高齢化社会の介護課題における世界の参照事例だ。65歳以上が人口の29%を占め——世界のどの国よりも高い割合——そして子供が高齢者ケアの主要な責任を負う親孝行（<em>親孝行</em>）という長年の文化的伝統を持つ日本は、その社会インフラが想定していなかった介護負担に直面している。
  </p>
  <p>
    一人暮らしの高齢日本人の割合は、都市化、変化する家族構造、および大都市での就職を求める若い世代の地理的移動性に driven されて、過去30年間で劇的に増加した。2024年には、65歳以上の高齢日本人約700万人が一人暮らしをしており、この数は2040年までに1000万人を超えると予測されている。これらの個人の成人した子供たちは東京、大阪、名古屋に不均衡に集中しており、毎日の物理的な介護を不可能にする距離によって親から引き離されている。
  </p>
  <p>
    <em>孤独死</em>は日本で認識された社会現象となり、一人で暮らす高齢者が何日も何週間も発見されずに亡くなる事例が年間推定3万〜5万件ある。この現象は単に身体的健康の低下の結果ではない；情報格差の結果——一人暮らしの高齢者が夜間に起きなかったり、医療緊急事態を経験したりしたことを誰もリアルタイムに知らないということ——だ。
