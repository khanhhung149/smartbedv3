  <h2>脅威の状況：何が問題になりうるか</h2>
  <p>
    睡眠データへの具体的なプライバシー上の脅威を理解することで、エンジニアリングの選択がなぜ重要かを枠組みできる。
  </p>
  <p>
    <strong>データブローカーへの販売。</strong>消費者向け健康・ウェルネスアプリは、ユーザーデータをデータブローカー——個人データプロファイルを集約して再販するビジネスモデルを持つ企業——に販売・共有した実績がよく文書化されている。2020年のBritish Medical Journal誌の調査では、人気健康アプリ24本のうち19本が、しばしばユーザーの認識なしに、広告ネットワークやデータブローカーを含む第三者とデータを共有していることが判明した。生または処理されたデータを中央サーバーにアップロードする睡眠追跡アプリは、まさにブローカーが求めるデータ資産を作り出す。
  </p>
  <p>
    <strong>データ侵害。</strong>健康データはブラックマーケットで最も価値の高いカテゴリの一つだ。医療記録はクレジットカード番号より桁違いに高い値がつく。なぜなら健康データは保険詐欺、処方薬詐欺、標的型ソーシャルエンジニアリング攻撃に使用できるからだ。何千人ものユーザーの何年分もの健康データを集中化した睡眠追跡プラットフォームは、高価値の攻撃ターゲットを作り出す。
  </p>
  <p>
    <strong>保険差別。</strong>強力な遺伝子非差別保護のない管轄域では、消費者デバイスから得た健康データが保険引受決定に使用されてきた。睡眠障害指標——無呼吸を示す呼吸イベント指数、心臓リスクに関連するHRVパターン——は、保険引受業者がアクセスできれば、インフォームドコンセントなしにこの使用について保険料や補償決定に影響を与える可能性がある。
  </p>
  <p>
    <strong>法執行機関のアクセス。</strong>会社のサーバーに保存されたデジタル健康データは、それらのサーバーが置かれている管轄域での法的プロセス——召喚状、裁判所命令、法執行機関の要請——の対象となる。睡眠パターンデータは理論上、刑事または民事手続きの状況証拠として使用される可能性がある。
  </p>

