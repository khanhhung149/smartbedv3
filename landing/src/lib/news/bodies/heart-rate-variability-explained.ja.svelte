  <h2>HRVの数学：RMSSD、SDNN、LF/HF</h2>
  <p>
    HRVを定量化するためにいくつかの数学的手法が使用されており、それぞれ基礎となる生理学の異なる側面を強調している。消費者向け健康デバイスで最もよく使われるのは<strong>RMSSD</strong>（連続差の二乗平均平方根）だ。連続する拍動間隔の差の二乗の平均の平方根で、特に副交感神経（迷走神経）の調節に敏感で、急性ストレスや回復に素早く反応するため、日々のモニタリングに適している。
  </p>
  <p>
    <strong>SDNN</strong>（NN間隔の標準偏差）は交感神経と副交感神経の両成分を含む全体的な変動性を捉える。長い測定ウィンドウほど高くなる傾向があり、特に心臓リスク層別化研究でHRVを評価した元来の方法である24時間ホルター監視で、より臨床的な文脈で使われる。
  </p>
  <p>
    周波数ドメイン解析はHRV信号をその成分周波数に分解する。<strong>低周波数（LF、約0.04〜0.15 Hz）</strong>帯は交感神経と副交感神経の混合活動を反映する。<strong>高周波数（HF、約0.15〜0.4 Hz）</strong>帯は呼吸周波数と密接に対応し、主に副交感神経（迷走神経）活動を反映する——これが各呼吸サイクルに伴う心拍数の自然な加速と減速である呼吸性洞性不整脈だ。LF/HF比は交感迷走神経バランスの指数として用いられてきたが、その解釈は単純な「交感神経/副交感神経比」として説明されるよりも繊細だ。
  </p>

