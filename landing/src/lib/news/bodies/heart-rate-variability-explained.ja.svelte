  <p>
    あなたが今まで経験したすべての心拍は、直前の心拍とわずかに異なっている。劇的でも心配する必要もない差異だ——心臓が誤作動しているわけではない——しかし拍動間の正確なミリ秒単位のタイミングが毎回異なる。この変動は心臓のメカニズムの欠陥ではない。それは意図された生物学的シグナルであり、自律神経系が休息と準備の間でリアルタイムに行うネゴシエーションの読み取り値だ。心拍変動（HRV）はそのシグナルを読み解く科学であり、睡眠中ほどそれが明確に語りかけてくる時はない。
  </p>

  <h2>HRVが実際に何を測るか</h2>
  <p>
    HRVを理解するには、まず心拍数を駆動するものを理解する必要がある。心臓には固有のペースメーカー——洞房結節——があり電気インパルスを生成するが、独立して動いているわけではない。自律神経系の2つの分岐がそのリズムを継続的に調節している。交感神経系（「闘争または逃走」の分岐）は心拍を速め、副交感神経系（「休息と消化」の分岐、主に迷走神経が媒介）は遅らせる。
  </p>
  <p>
    ストレスや身体的な負荷状態では、交感神経が優位になる。心拍数は上昇し、決定的なことに、拍動間の間隔はより規則的で機械的なリズムに近くなる。高需要モードのときは変動の余地が少ない。休息と回復の状態では、副交感神経活動が高まる。心拍数は低下し、拍動間隔はより変動的になる——ある拍動は長く、ある拍動は短く——神経系が常に行っている微細な調整を反映した複雑で数学的に構造化されたパターンとして。
  </p>
  <p>
    これは多くの人がHRVを初めて知ったときに驚くパラドックスだ：<strong>変動性が高い方が一般的に健康的</strong>だということ。完璧に機械的な規則性で拍動する心臓は最適な健康状態ではなく、ストレス・疲弊・基礎疾患に関連することが多い自律神経的硬直性の状態にある。豊かで複雑な変動性を示す心臓は、その調節システムが変化する要求に柔軟に対応できる余裕があることを示している。
  </p>

