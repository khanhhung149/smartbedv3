  <h2>睡眠中のHRV：夜の自律神経アーキテクチャ</h2>
  <p>
    睡眠は覚醒の受動的な停止ではない。活発に協調された生物学的プロセスであり、自律神経系は一晩を通じて深く関与している。睡眠中のHRVは、体が夜をどれだけ効果的に回復に使っているかについて、驚くほど詳細なストーリーを語る。
  </p>
  <p>
    <strong>非レム段階N1とN2</strong>（浅い睡眠）では、自律神経活動が覚醒の要求から深い回復の副交感神経優位へと移行を始める。交感神経の撤退が迷走神経緊張を高めるにつれ、HRVは覚醒時より増加する傾向がある。
  </p>
  <p>
    <strong>N3徐波睡眠</strong>（深い睡眠）では、副交感神経優位が最大に達する。心拍数は夜の最低点に下がる。HRVはピークに達する。呼吸は遅くなり規則的になる。これは最も深い身体的回復が起きるステージだ——成長ホルモンが夜の主要なパルスで放出され、組織修復が加速し、心血管系が最も深い休息を経験する。N3中のHRVは睡眠の質の最も強力な単一エポック指標の一つだ：N3 HRVが高ければ、回復はおそらく順調に進んでいる。
  </p>
  <p>
    <strong>レム睡眠</strong>では、自律神経の状況が劇的に逆転する。レムは自律神経の不安定性を特徴とし——心拍数が上昇し、呼吸数が増加して不規則になり、HRVが急落する。交感神経活動の急増が夢を駆動する強烈な皮質活性化に伴う。これは病的ではない；正常なレム生理だ。しかし、長引いた、断片化した、またはレム優位の睡眠が必ずしも回復感をもたらさない理由でもある：神経系が深睡眠の低需要・高回復の自律神経状態に十分な時間を費やしていないからだ。
  </p>

  <h2>SleepTechが皮膚接触なしでHRVを測定する方法</h2>
  <p>
    従来のHRV測定には、ECG（心臓の電気活動からR-R間隔を直接捉えるゴールドスタンダード）またはフォトプレチスモグラフィー（PPG）センサー——ほとんどのスマートウォッチ背面の緑色LEDを使う——のどちらかが必要だ。どちらの方法も体との直接接触が必要だ。ECGは皮膚への電極配置が必要で、PPGは通常手首または指の血管に対して押し当てる必要がある。
  </p>
  <p>
    YumePadシステムは根本的に異なる物理的原理を使う：心弾動図（BCG）だ。心臓が収縮して大動脈に血液を送り出すとき、その射出の機械的反動——微小だが測定可能——が体を通じてそれを支えているあらゆる面に伝播する。マットレス下の高感度力センサーがこの微振動を検出する。各心拍が、心臓周期の特定の相に対応する一連のラベル付きピーク（I、J、K、L波）を持つ特徴的なBCG波形を生成する。
  </p>
  <p>
    拍動間隔は連続するJピーク（またはモデル由来の等価物）のタイミングから推定され、「心弾動図拍動間間隔」（BCG-IBI）と呼ばれるものを生成する。適切な信号処理——体動アーチファクト除去、呼吸信号の分離、MLベースのピーク検出——により、BCG-IBIは睡眠の文脈でのHRV解析に十分な精度でECG由来のR-R間隔に近似できる。BCG由来HRVを同時ECG参照と比較した独立的検証研究では、制御された条件下でRMSSDの平均絶対誤差が5 ms未満であることが示されており、縦断的トレンドモニタリングの臨床的に意味のある範囲内だ。
  </p>

