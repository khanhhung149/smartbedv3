  </blockquote>

  <h2>略史：ゴードンからガートナーまで</h2>
  <p>
    BCGの歴史は再発見の物語だ。1877年のゴードンの観察は記録されたが系統的には発展しなかった。スターの1939年の装置はその時代には洗練されていたが、条件——機械的に隔離されたプラットフォーム、制御された実験室環境——が臨床展開を妨げた。1940〜50年代にかけて、BCGは心拍出量、弁機能、冠動脈疾患との相関を示すBCG波形パラメーターの実質的な研究成果を生み出した。J波の振幅とI-J間隔は心臓収縮力の潜在的なマーカーとして同定された。
  </p>
  <p>
    この技術は心臓評価のより強力なツールとして心エコー図と核医学心臓病学が登場した1960〜70年代に廃れた。BCGは歴史的な珍品のように見えた——生理学的に興味深いが臨床的に時代遅れになった。技術は約30年間休眠状態に入った。
  </p>
  <p>
    復活は2000年代初頭に始まり、当初は高齢者ケア向けの邪魔にならないバイタルサインモニタリングに興味を持つ学術グループが牽引した。画期的な論文はMIT、ジョージア工科大学、そして大阪を含むいくつかの日本の大学のグループから来た。大阪では、ウェアラブルデバイスのコンプライアンス負担なしに在宅高齢化集団をモニタリングする必要性が、実際の家庭の実際のベッドでBCGを機能させる強力な動機を生み出していた。
  </p>
  <p>
    2012年に大阪でSleepTechを創業したチームには、2000年代中頃から高齢者モニタリング向けBCG信号処理に取り組んでいた研究者が含まれていた。学術研究プログラムから消費者製品への移行には、センサーのマットレスパッド厚への小型化、現実世界のノイズに対してロバストなMLモデルの開発、低消費電力組み込みハードウェア上で必要なサイクルで推論を実行するための計算パイプラインの構築という3つの異なるエンジニアリング問題を解決することが必要だった。
  </p>

