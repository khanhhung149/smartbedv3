  <p>
    YumePadの内部技術は、1877年のスコットランド人医師アレクサンダー・ゴードンへと知的系譜をたどることができる。彼は、静止した患者の体が各心拍とともにわずかに反動することを初めて系統的に記録した。1939年にはペンシルバニア大学のアイザック・スターが専用の台座式装置を製作してこの微小運動を定量的に計測し、「心弾動図（ballistocardiograph）」という用語を生み出した。その後数十年間、BCGは臨床心臓病学において活発ながら最終的には周辺的な役割を占めた——物理学的には興味深いが、臨床採用は限られていた。そこへMEMSセンサー、エッジコンピューティング、機械学習の組み合わせが到来し、ガス燈の時代に発展した計測原理が世界で最もアクセスしやすい継続的心臓モニタリング技術のエンジンへと変貌した。
  </p>

  <h2>BCGの物理学：体がマットレスに何を伝えるか</h2>
  <p>
    BCGの基礎となる機械的原理は明快だ。心臓が収縮して大動脈に血液を送り出すたびに、ニュートンの第3法則が適用される。血液の射出は血液に力を及ぼし、血液は体に等しく逆向きの反力を及ぼす。この反力——弾道力と呼ばれる——は小さい（典型的な心拍出量に対してミリニュートン程度）が、測定装置が十分に感度を持ち体に機械的に結合していれば計測可能だ。
  </p>
  <p>
    スターの原装置では、患者は低摩擦で水平方向に自由に移動できる自由懸架台の上に横たわっていた。各心拍による台の変位をトランスデューサーで測定した。結果として得られる波形——BCG——は特徴的な形状を持つ：心臓の機械的サイクルの異なる相に対応するI、J、K、L、M、N波と呼ばれる一連の波だ。最大の正の偏向であるJ波は心臓射出のピークに対応する。K波は血流が血管抵抗に遭遇して減速する際の負の偏向だ。
  </p>
  <p>
    現代のBCGセンサーは自由懸架プラットフォームを必要としない。ピエゾ電気フィルム、ひずみゲージ、静電容量式力センサーが臨床グレードの信号抽出に十分な感度でマットレスを通じて伝達される微小機械力を検出できる。課題は物理学から信号処理へと移行した。すなわち、望ましいBCG信号を呼吸体動アーチファクト、共有ベッドでのパートナーの体動、そして実際の家庭環境の交通・空調システム・その他の家庭騒音源からの広帯域環境振動ノイズフロアから分離することだ。
  </p>

  <blockquote>
    <p>「スターのインサイトは、体全体がトランスデューサーだということだ。心臓の機械的な仕事は、それが接触するすべての組織と面に伝播する。私たちはただ十分に注意深く聴く必要があった」</p>
