  <h2>BCG対PPG対ECG：信号の比較</h2>
  <p>
    他の主要な心臓センシングモダリティとの関係でBCGがどこに位置するかを理解することで、BCGが何を得意とし限界がどこにあるかが明確になる。
  </p>
  <p>
    <strong>ECG（心電図）</strong>は体表面の電圧差を検出することで心臓の電気活動を計測する。ECG R波——心室脱分極に対応する大きな正のスパイク——はサブミリ秒の精度でR-R間隔測定を可能にする非常に正確な心臓タイミングを提供する。ECGは不整脈検出、心臓伝導解析、HRV計測のゴールドスタンダードだ。アンビエント睡眠モニタリングへの制限は、皮膚電極接触が必要なことだ。
  </p>
  <p>
    <strong>PPG（フォトプレチスモグラフィー）</strong>は血液が組織を脈動する際の光吸収量を検出することで血流の容積変化を計測する。スマートウォッチ背面のLEDセンサーはPPGセンサーだ。便利だが、心臓の電気的イベントに対する遅延（「脈波伝播時間」）を導入し、末梢灌流と体動アーチファクトによって精度が変動し、体との接触が必要だ。
  </p>
  <p>
    <strong>BCG</strong>は支持面への体を通じた伝達として、心臓の血液射出によって生み出される機械的力を計測する。体との接触を必要としない。BCGの心臓サイクルとの時間的関係はECGより複雑だが、睡眠解析で使用されるエポックレベル（30秒ウィンドウ）の統計には十分な精度が保たれる。
  </p>
  <p>
    <strong>BCGの重要な優位性</strong>は制御された比較でECGやPPGより生の信号品質が優れているということではない——そうではない。優位性は体との接触なしに動作することであり、ユーザーからの行動要件なしに100%の夜間計測コンプライアンスを達成できる唯一のモダリティにしている。
  </p>

  <h2>現代のBCG信号処理：AIが振動から健康を抽出する方法</h2>
  <p>
    実際のマットレス下のセンサーが捉えるBCG信号は教科書のクリーンな波形とは程遠い。望ましい心臓信号と複数のノイズ源の重ね合わせだ：呼吸体動（低周波数成分を支配する）、姿勢変換（心臓信号より桁違いに大きいステップ関数アーチファクト）、共有ベッドでのパートナーの体動、交通・空調システム・その他の家庭騒音源からの環境振動。
  </p>
  <p>
    現代のBCG処理パイプラインはこれを層状に対処する：<strong>適応バンドパスフィルタリング</strong>がBCG心臓コンテンツを含む周波数帯（約1〜15 Hz）を分離しながら呼吸体動（~0.5 Hz以下）と高周波ノイズを除去する。<strong>姿勢変換検出</strong>が体の位置変換に関連する大振幅アーチファクトを識別し、これらのウィンドウを心臓解析からマスクする。<strong>マルチセンサー融合</strong>がデュアルゾーン構成でセンサー間の空間的分離を使用して共有ベッドの2ユーザーを識別する。<strong>ピーク検出と拍動間間隔推定</strong>がテンプレートマッチングとMLベースのピーク分類を組み合わせてクリーニングされた信号のJ波を識別する。<strong>睡眠ステージ分類</strong>が心臓タイミング特徴、呼吸数・深さ特徴、体動特徴を時間的モデル（LSTMまたはTransformerアーキテクチャ）に統合し、各30秒エポックを覚醒・N1・N2・N3・REMに分類する。
  </p>

