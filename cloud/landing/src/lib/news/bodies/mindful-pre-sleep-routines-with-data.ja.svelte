  <h2>ウィンドダウン儀式が機能する理由：生理学</h2>
  <p>
    睡眠開始はイベントではなく、開始までに時間を要する生理的移行のカスケードだ。深部体温が下がり始める必要がある。光への暴露が減ることでトリガーされるメラトニン分泌が高まる必要がある。交感神経系は徐々に副交感神経の優位性に譲る必要があり、これは睡眠開始前に上昇するHRVに反映される。朝に最高値に達し、夜には最低値に近づくはずのコルチゾールが低くなければならない。これらの移行は生物学的な床より下に急がせることはできないが、——しばしば大幅に——就寝前の誤った行動によって遅延させることができる。
  </p>
  <p>
    青色スペクトルの明るい光（スマートフォン、タブレット、ほとんどのLEDスクリーンが発するもの）は、約90分の潜時でメラトニン産生を抑制する。夕方のスマートフォン使用が1時間あるだけで、睡眠開始が測定可能なほど遅れ、夜の前半の徐波睡眠の割合が低下することがある。認知的な関与——メールへの返信、ストレスのあるニュースの確認、SNSの比較ループ——は交感神経のトーンを高め、コルチゾールを上昇させ、睡眠への生理的な降下に直接対抗する。就寝の2〜3時間以内の激しい運動は深部体温と交感神経活動を高め、同じ遅延効果をもたらす。
  </p>
  <p>
    うまく設計されたウィンドダウンルーティンはこれらの障害それぞれに対処する：メラトニンの上昇を可能にするために光への暴露を減らし、認知活動を刺激する活動を落ち着かせるものに置き換えて交感神経のトーンを下げ、深部体温が自然に低下し始めることを許す。このメカニズムを理解することで、どんな単一の要素よりも、活動の特定の組み合わせとタイミングが重要な理由が説明できる。
  </p>

  <h2>日本のお風呂の伝統：休息前の温もり</h2>
  <p>
    日本では何世紀もの間、夕方の入浴儀式——<em>お風呂</em>——が実践されてきたが、これが睡眠科学と驚くほどよく一致していることが分かっている。伝統的なお風呂は通常、就寝の1〜2時間前に高温の湯（通常40〜42℃）に15〜20分間全身浴するものだ。その後に続くシーケンスが睡眠への恩恵の核心だ：お風呂は末梢皮膚温度を劇的に上昇させ、体の体温調節反応をトリガーする——皮膚表面から熱が放散されることで深部体温が下がり始める。この能動的な体温降下は、深い睡眠に先立つ自然な体温調節の降下を加速させる。
  </p>
  <p>
    Sleep Medicine Reviewsに発表された研究は、約5,000件の研究からデータを分析し、就寝の1〜2時間前に温浴または温かいシャワーを浴びることが——特に水温が40〜43℃の場合——入眠潜時を平均10分短縮し、全体的な睡眠の質を改善することを見つけた。そのメカニズムは上述の体温調節カスケードそのものだ：温かい入浴は深部体温の反跳的な低下を生じさせ、生物学的睡眠シグナルをトリガーする。
