  <h2>過剰最適化のトラップ</h2>
  <p>
    寝室にデータを持ち込むことには現実的なリスクがある：<em>オルソソムニア</em>——睡眠メトリクスへの不安な執着で、逆説的に睡眠を悪化させる可能性がある。目覚めてすぐに睡眠スコアを確認し、HRVが「良かった」と知るまでリラックスできず、1つのメトリクスを最適化するために夕方全体を調整する人は——より良く眠っていない。彼らはコルチゾールを上昇させ睡眠を断片化する、まさにパフォーマンス不安を導入している。
  </p>
  <p>
    SleepTechのこの点に関するデザイン哲学は明確だ：データは毎晩ではなく週次でレビューすべきだ。起床後の前夜のサマリーへのちらっとした確認は、30分ではなく30秒で十分だ。7日または30日にわたるトレンドビューは、単一の夜のスコアより意味がある。データの目標は、どの習慣が本当に機能しているかを特定し、注意を要する変化を検出することだ——就寝前の不安の新たな源を作ることではない。
