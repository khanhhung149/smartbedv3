  <h2>アプリによるBluetoothペアリング</h2>
  <p>
    プライマリペアリングデバイスとして機能するデバイス——通常は親のスマートフォン（お持ちの場合）、またはセットアップを主に家族が管理する場合はあなたのスマートフォン——にSleepTechアプリをダウンロードします。アプリを開き「新しいデバイスを追加」をタップします。アプリがハブとのBluetoothペアリングをガイドします；プロセスは約90秒かかり、技術的な知識は不要です。ハブはシリアル番号の最後の4文字を使って自動的に名前が付けられます；わかりやすくするために、アプリ設定で「お母さんの部屋」などの名前に変更できます。
  </p>
  <p>
    親がAndroid 10以前のAndroidデバイスを使用している場合は、アプリに位置情報の許可が付与されていることを確認してください——これは古いAndroidバージョンでのBluetoothデバイス検出のシステムレベルの要件であり、アプリが他の目的でお客様の位置を使用することを意味しません。iPhone 7以降のiOSデバイスとAndroid 11以降はこの許可が不要です。
  </p>

  <h2>家族の招待の設定</h2>
  <p>
    家族の招待は、YumePadを個人的な睡眠トラッカーから介護ツールに変える機能です。アプリのメインメニューから、親は設定→家族共有→家族を招待に移動します。メールアドレス（またはSMSで通知を受け取りたい場合は電話番号）を入力します。招待リンクを受け取り、承認すると、そこから、親が共有することを選択した毎晩の概要を受け取ります。
  </p>
  <p>
    招待フローは意図的に高齢者によって開始されるように設計されており、家族のメンバーによってではありません。これは技術的な制約ではありません——逆の方法で設計することも簡単でしょう——しかし、SleepTechのデータガバナンス原則を反映した意図的な選択です。高齢者がデータのオーナーです。彼らがあなたを招き入れます。彼らはいつでも同じ設定メニューからアクセスを取り消すことができます。
  </p>
  <p>
    共有ビューを設定する際、親はあなたに送信されるアラートタイプも設定できます。オプションには：毎晩の概要（常に利用可能）、睡眠の質の異常アラート（夜がベースラインから大幅に逸脱した場合）、ベッド退出時間アラート（転倒防止のため）、心拍異常アラート（睡眠中の安静時心拍がベースラインから大幅に逸脱した場合）が含まれます。ほとんどの家族は、毎晩の概要と睡眠の質の異常アラートから始め、転倒リスクが特定の懸念である場合はベッド退出アラートを追加します。
  </p>

  <h2>ベースライン学習期間：3〜7夜</h2>
  <p>
    YumePadとの最初の1週間について理解すべき最も重要なことは、システムが学習中だということです。すべての個人は独自の睡眠生理を持っています——異なる睡眠段階での特徴的な心拍パターン、典型的な呼吸数の変動、習慣的な就寝・起床時刻、夜間の正常な動きのパターン。YumePadは最初の7夜のデータから個人的なベースラインモデルを構築し、このベースラインが後の異常検出を意味のあるものにします。
  </p>
  <p>
    この学習期間中、アプリが表示するデータは正確です——睡眠段階分け、心拍数、呼吸数の数値はセンサーが実際に測定していることを反映しています——しかし、異常検出とトレンド分析機能は無効になっているか、「ベースライン不足」と明確に表示されています。2週目以降に比べて、睡眠の質スコアが変動することがあります。これは正常です：システムはモデルを構築中であり、初期の夜のデータは1週間以上蓄積されたデータよりも不確実性が高いです。
  </p>
  <p>
    家族はベースライン期間を短縮できるかどうか尋ねることがあります。答えは：最小信頼性ベースラインは、基本的な睡眠段階モデルには3夜、完全な異常検出モデルには7夜です。最初の3夜が一貫した信号品質を示す場合、非常に重要な逸脱（大きな心拍変化、非常に長いベッド退出イベント）に対する異常検出は4夜目から利用可能になります。
  </p>

