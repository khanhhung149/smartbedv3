  <h2>物理的な設置：パッドの下ではなくマットレスの下に</h2>
  <p>
    YumePadの設置は5分以内に完了します。センサーパッド——約60cm×40cm、小さな枕ほどのサイズ——は、親の胴体の寝ている部分を中心に、マットレスの下にスライドして入れます。パッドはマットレスとベッドベース（またはボックススプリング、スラット、プラットフォームフレーム）の間に置く必要があります——マットレスとボックスシーツの間ではありません。センサーは、心拍と呼吸の微振動を検出するために、上にマットレスの重みが必要です。
  </p>
  <p>
    位置決めは重要です。YumePadのセンサーゾーンはパッドの中央上部3分の1に位置しており、これは親が通常の姿勢で眠るときの胸と上腹部の下に位置するよう配置する必要があります。親がベッドの中央で眠る傾向がある場合は、それに合わせてパッドを中央に配置します。片側に習慣的に眠る場合は、センサーゾーンが寝る位置の下にくるようにパッドをオフセットします。
  </p>
  <p>
    パッドは、薄いケーブルを介して小型のハブユニット——大きなマッチ箱ほどのサイズ——に接続し、ケーブルはベッドの側面に沿って走ります。ハブは標準的なコンセントに差し込み、アプリを介してBluetooth接続します。ハブのシングルグリーンLEDが点灯すれば、センサーが信号を受信していることを確認できます。LEDが琥珀色に点滅している場合は、パッドが十分な信号を検出していません——通常、寝るゾーンの中心にもう少し近づけるか、マットレスが異常に厚いまたは密度が高い場合です。アプリのトラブルシューティングガイドが2分以内に3つの最も一般的な位置決めの問題を説明しています。
  </p>

