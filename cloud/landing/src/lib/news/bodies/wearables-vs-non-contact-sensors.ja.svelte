  <h2>精度：各カテゴリが得意なことと苦手なこと</h2>
  <p>
    両カテゴリはPSG（ポリソムノグラフィー）——実験室のゴールドスタンダード——に対する独立した学術的検証を受けている。現在の研究の正直なまとめ：
  </p>
  <p>
    <strong>総睡眠時間（TST）：</strong>ウェアラブルと非接触センサーの両方が通常の睡眠者でのTST推定において通常PSG推定値の10〜15%以内で適切に機能する。ウェアラブルは睡眠不良者でTSTを過大評価する傾向があり（静かな覚醒を浅い睡眠として扱う）、BCGセンサーは非常に静止した睡眠者でTSTを過小評価することがある。
  </p>
  <p>
    <strong>睡眠ステージ分類：</strong>Oura Ringはウェアラブルの中で最善の精度を示しており、一部の検証研究では4段階分類（覚醒/浅い/深い/REM）でPSGとのエポック毎の一致が約75〜78%を示している。Apple WatchとWhoopは研究と集団によって68〜74%の範囲だ。YumePadを含むBCGベースシステムは独立的検証で同等または若干低い4段階精度（65〜75%）を示しており、主要な制限はN1検出——BCGの心肺信号がN2と信頼性高く区別するのが難しい最も浅いNREMステージだ。
  </p>
  <p>
    <strong>HRV測定：</strong>ここで比較はより微妙になる。手首PPG HRV測定は異なる睡眠姿勢——特に腕を体の下に入れたり伸ばしたりした横臥——による体動アーチファクトの影響を受ける。リングベースPPG（Oura）は体動結合の低減と血管近接性の改善により良好に機能する。YumePadのBCG由来HRVは制御された検証研究でOura Ringと同等の精度を達成し、ECG参照に対してRMSSDの平均誤差は通常5〜7ms未満だ。
  </p>
  <p>
    <strong>呼吸イベント検出：</strong>BCGシステムはここで意味深な優位性を持つ。呼吸はBCG波形を変調する方法で、訓練されたMLモデルが呼吸数の推定、周期的呼吸パターンの検出、睡眠関連呼吸障害に関連する潜在的な呼吸イベント指数（REI）のフラグ付けを可能にする。
  </p>

  <h2>快適性とコンプライアンスの方程式</h2>
  <p>
    精度の仕様は、デバイスが実際に継続的に装着されなければ見かけほど重要ではない。これは睡眠トラッカー精度比較についての不快な真実だ：デバイスの実際の長期精度はその技術的精度とコンプライアンス率の積だ。80%の精度を持つが60%の夜しか装着されないデバイスは、72%の精度を持ち97%の夜に装着されるデバイスよりも悪い縦断データを生成する。
  </p>
  <p>
    <strong>ウェアラブルのコンプライアンス障壁</strong>には：充電頻度（Apple Watchは毎晩；WhoopとOuraは週1回程度）、充電タイミング（睡眠窓中の充電がデータセットを途切れさせる）、睡眠中の物理的不快感（圧迫跡、熱感、デバイスの固有感覚的意識）、「悪い」夜の忘れや意図的な回避——まさにデータが最も臨床的に興味深い夜。
  </p>
  <p>
    <strong>長期的な皮膚接触の懸念</strong>も特に言及に値する。消費者向けウェアラブルPPGセンサーについて急性健康リスクは確立されていないが、継続的な装着で接触性皮膚炎、圧迫跡、皮膚刺激を報告するユーザーの割合は小さいが無視できない。これは小児への使用と敏感な皮膚状態のユーザーに特に関連する。デバイスを装着することの固有感覚的意識——深いリラクゼーションを妨げる「監視されている感覚」——から睡眠障害を報告する個人もいる。
  </p>
  <p>
    <strong>非接触センサーのコンプライアンス</strong>は構造的に異なる。マットレスの下に一度設置すれば、覚えることも、充電することも、物理的に我慢することも何もない。コンプライアンスはユーザーが監視されているベッドで眠る限り本質的に100%だ。これが縦断モニタリングにおける最も強力な優位性だ：データセットにユーザー行動に起因するギャップがない。
  </p>

