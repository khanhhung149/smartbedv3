  <p>
    アジア、欧州、北米のどのドラッグストアや電器店に入っても、睡眠追跡の選択肢が棚を埋めている。スマートウォッチ、フィットネスバンド、リング、クリップ式パルスオキシメーター、そして——増加傾向にある——マットレスの下に滑り込ませる薄いパッド。消費者向け睡眠テクノロジー市場は急速に多様化し、どのタイプのデバイスを使うかという選択はもはや単純ではない。本稿では2つの主要カテゴリ——手首装着型ウェアラブルとマットレス下非接触センサー——を、長期的な睡眠健康モニタリングにおいて実際に重要な次元で比較する。
  </p>

  <h2>ウェアラブル：成熟しているが制約のあるカテゴリ</h2>
  <p>
    手首装着型睡眠トラッカーは2011年のFitbitの最初の睡眠追跡ファームウェアアップデート以来、主流となっている。今日、このカテゴリは3つのデバイスが支配している：Apple Watch（世界的に最も普及したスマートウォッチ）、Whoop（サブスクリプション制、画面なし、アスリート向け）、Oura Ring（指装着型リングで、バイオハッカーや経営幹部の間で人気）。いずれも概ね似たようなセンシング技術を使用している：皮膚を通じた血流から心拍数と心拍変動を推定するフォトプレチスモグラフィー（PPG）と、体動検出のための加速度計の組み合わせだ。
  </p>
  <p>
    <strong>Apple Watch</strong>は最も機能豊富だが、3つの中で最も多目的でもある。睡眠追跡は有能だが、主要設計目的ではない——このウォッチはまずコミュニケーションデバイスであり、次にフィットネストラッカー、3番目に睡眠モニターだ。睡眠ステージ検出は心拍数、HRV、体動データの組み合わせを使用する。独立した検証研究によれば、総睡眠時間と主要な覚醒エピソードの検出は適切に行うが、REM対非REMのステージング精度は低い。バッテリー寿命が主要な制約だ：ほとんどのモデルが毎日充電を要し、充電ルーティンが典型的に就寝前の落ち着き時間か早朝の時間窓を妨げる——まさに縦断データが最も重要な時間帯だ。
  </p>
  <p>
    <strong>Whoop</strong>は異なる哲学を取る。生理的モニタリング専用に設計されており、画面なし、通知なし、睡眠中を含めて常時装着する。4〜5日のバッテリー寿命により、Apple Watchの睡眠追跡を悩ます充電の摩擦が解消される。WhoopのHRVと回復スコアはプロスポーツおよびエリートトレーニング環境の参照指標となっている。睡眠ステージングはApple Watchより詳細で、呼吸数指標も含まれる。サブスクリプションモデル（月約30ドル）は初期デバイスコストはないが継続費用がかかる。
  </p>
  <p>
    <strong>Oura Ring</strong>は興味深い位置を占める：手首ではなく指で測定し、手首より優れたPPG信号を提供する（指は手首より体動アーチファクトが少なく血管近接性が良い）。睡眠ステージング精度は複数のピアレビュー研究で手首PPGより意味深く優れていることが独立的に検証されている。リングの形状は睡眠中のほとんどのユーザーに目立たず快適だ。Whoopのようにサブスクリプションモデルはデバイスコストとは別だ。バッテリー寿命は4〜7日。温度センサーが月経周期相検出と初期疾患検出に有用な次元を加える。
  </p>

  <blockquote>
    <p>「最善の睡眠トラッカーとは毎晩実際に装着されるものだ。快適性、利便性、バッテリー寿命が、わずかな精度の差よりも長期的なコンプライアンスを決定する」</p>
    <footer>— Rebecca Chen博士、睡眠テクノロジー研究、シンガポール国立大学</footer>
  </blockquote>

  <h2>非接触センサー：異なる設計哲学</h2>
  <p>
    マットレス下センサーは睡眠追跡の問題への根本的に異なる答えを代表する。体に機器を装着するのではなく、寝床の表面に機器を装着する。コアとなるセンシング原理——心弾動図（BCG）——は、眠っている体を支えるあらゆる面を通じて伝播する、心拍と呼吸によって引き起こされる機械的微振動を検出する。
  </p>
  <p>
    2012年の大阪での創業からSleepTechが開発したYumePadシステムはこのカテゴリの代表例だ。薄いセンシングパッド（約2〜3mm厚）がマットレス下またはマットレスとマットレストッパーの間に滑り込む。ユーザーとの物理的接触は不要だ。装着するものも、就寝前に充電するものも、覚えておくものも何もない。センサーはコンセントから電源を取り、ホームネットワークへの継続的な接続を維持し、処理された睡眠データをSleepTechプラットフォームに送信する。AIモデルが睡眠ステージを分類し、HRVを計算し、呼吸イベントを検出し、夜間睡眠レポートを生成する。
  </p>

