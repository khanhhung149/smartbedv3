  <h2>เรื่องราวกรณีศึกษา: ยูกิและแม่ในชิซูโอกะ</h2>
  <p>
    ยูกิ ทานากะ อายุ 44 ปี ผู้จัดการโครงการในบริษัทการผลิตในโอซาก้า แม่ของเธอ ฟูมิโกะ อายุ 81 ปี อาศัยอยู่คนเดียวในบ้านในชิซูโอกะที่ยูกิเติบโตมา ห่างออกไปสองชั่วโมงครึ่งด้วยรถไฟความเร็วสูง ฟูมิโกะมีสุขภาพร่างกายดีสำหรับอายุของเธอ แจ่มใส เป็นอิสระ และต่อต้านอย่างแข็งขันต่อแนวคิดการย้ายไปสถานดูแลหรือแม้แต่การรับผู้ช่วยดูแลที่บ้านเป็นประจำ "เธออยากล้มดีกว่า" ยูกิพูดครั้งหนึ่ง ครึ่งหัวเราะ
  </p>
  <p>
    ความกังวลเริ่มต้นสามปีก่อนเมื่อฟูมิโกะมีอาการสับสนในเวลากลางคืนสั้นๆ เธอลุกขึ้นเพื่อเข้าห้องน้ำ หลงทางในทางเดินมืด และนั่งอยู่บนพื้นสี่สิบนาทีก่อนที่จะกลับเข้านอนได้ เธอไม่ล้ม ไม่มีกระดูกหัก แต่เธอก็ไม่ได้บอกยูกิเกี่ยวกับมันจนกระทั่งสัปดาห์หลัง เกือบจะเป็นเรื่องผ่านๆ "ถ้าเธอล้มล่ะ? ถ้าเธอนั่งอยู่ที่นั่นตลอดคืนล่ะ?" ยูกิบรรยายความคิดนั้นว่าเป็นสิ่งที่อาศัยอยู่ด้านหลังจิตใจเธอตลอดเวลาแล้ว
  </p>
  <p>
    การตั้งค่า YumePad เป็นข้อเสนอของยูกิ กำหนดกรอบอย่างชัดเจนว่าเป็นอุปกรณ์ตรวจสอบสุขภาพการนอน เธออ่านเกี่ยวกับ HRV และการนอนหลับลึกในนิตยสารและคิดว่าแม่อาจสนใจเข้าใจการนอนของตัวเอง ฟูมิโกะตกลงด้วยความกระตือรือร้นมากกว่าที่ยูกิคาดหวัง "เธอชอบแนวคิดที่ว่ามันเกี่ยวกับสุขภาพของเธอ ไม่ใช่เกี่ยวกับฉันที่กำลังดูเธอ" ยูกิอธิบาย
  </p>
  <p>
    การเปลี่ยนแปลงในการนอนของยูกิเองรู้สึกได้ภายในสองสัปดาห์ เธอเริ่มตรวจสอบสรุปข้ามคืนของแอปทุกเช้าก่อนออกไปทำงาน: การดูสามสิบวินาทีที่ยืนยันว่าแม่นอนหลับตลอดคืน ไม่มีการออกจากเตียงนาน ไม่มีสัญญาณสัญญาณชีพผิดปกติ ในเช้าที่สรุปแสดงการนอนที่แตกกระจาย ยูกิจะโทรหาแม่เช้านั้นแทนที่จะรอการโทรวันอาทิตย์ปกติ ในเช้าหนึ่ง ฟูมิโกะบอกว่าเธอปวดหัวและรู้สึกไม่ค่อยดี ยูกิจัดให้ไปพบแพทย์วันนั้น อาการปวดหัวปรากฏว่าเป็นปัญหาความดันโลหิตที่ไม่มีอาการยกเว้นตอนกลางคืน
  </p>
  <p>
    "ฉันยังกังวลอยู่" ยูกิกล่าว "แต่มันต่างออกไป ก่อนหน้านี้ ฉันกังวลเพราะไม่มีข้อมูล ตอนนี้ฉันกังวลเฉพาะเมื่อมีอะไรบางอย่างที่ต้องกังวล นั่นเป็นประสบการณ์ที่แตกต่างกันอย่างสิ้นเชิง"
  </p>

  <h2>สังคมผู้สูงอายุของญี่ปุ่น: ขนาดของปัญหา</h2>
  <p>
    สถานการณ์ประชากรศาสตร์ของญี่ปุ่นทำให้เป็นกรณีอ้างอิงระดับโลกสำหรับความท้าทายการดูแลในสังคมผู้สูงอายุ โดย 29% ของประชากรอายุเกิน 65 ปี ซึ่งเป็นสัดส่วนสูงสุดของประเทศใดในโลก และด้วยประเพณีทางวัฒนธรรมที่หยั่งรากลึกของความกตัญญู (<em>oyakoko</em>) ที่วางความรับผิดชอบหลักในการดูแลผู้สูงอายุไว้ที่บุตรหลานที่เป็นผู้ใหญ่
  </p>
  <p>
    <em>โคโดคุชิ</em> (孤独死) — การตายในความโดดเดี่ยว — กลายเป็นปรากฏการณ์ทางสังคมที่ได้รับการยอมรับในญี่ปุ่น โดยมีกรณีที่ประมาณ 30,000–50,000 กรณีต่อปีที่ผู้สูงอายุที่อาศัยอยู่คนเดียวเสียชีวิตและไม่ถูกค้นพบเป็นเวลาหลายวันหรือหลายสัปดาห์ ปรากฏการณ์นี้ไม่ใช่แค่ผลที่ตามมาของการเสื่อมสุขภาพร่างกาย แต่เป็นผลที่ตามมาของช่องว่างข้อมูล ไม่มีใครรู้แบบเรียลไทม์ว่าผู้สูงอายุที่อาศัยอยู่คนเดียวไม่ตื่นหรือประสบเหตุฉุกเฉินทางการแพทย์ในตอนกลางคืน
  </p>
  <p>
    YumePad ของ SleepTech ได้รับการออกแบบในปี 2012 ที่โอซาก้าโดยคำนึงถึงบริบทนี้อย่างชัดเจน การตรวจจับการอยู่บนเตียง การติดตามคุณภาพการนอน และสถาปัตยกรรมการแชร์ครอบครัวของระบบตอบสนองต่อความท้าทายเฉพาะของลูกผู้ใหญ่ที่อยู่ห่างไกลซึ่งไม่สามารถอยู่ทางกายภาพได้แต่ต้องการรู้ว่าพ่อแม่ของพวกเขาไม่เป็นไรคืนนี้
  </p>

