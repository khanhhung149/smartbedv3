  <h2>5年間の変化：何がどう変わったか</h2>
  <p>
    この5年間で、3つの収束する技術革新がそのギャップを劇的に埋めた。
  </p>
  <p>
    <strong>第一に、センサーの小型化と感度向上。</strong>ピエゾ電気センサーとひずみゲージセンサーが、マットレス素材を数センチ透過して呼吸と心臓の弾動（心拍の機械的な力が体を通じて支持面に伝わる振動）が引き起こす微小振動を検出できるほど小型化・高感度化された。この心弾動図（BCG）信号は1930年代から臨床研究で知られていたが、実際の家庭環境の寝床から信頼性高く抽出することは、最新のMEMSセンサーと低ノイズ電子回路が登場するまで実現困難なエンジニアリング課題だった。
  </p>
  <p>
    <strong>第二に、クラウドおよびエッジコンピューティングの進化。</strong>生BCG信号は非常にノイズが多い。体動アーチファクト、パートナーの動き、呼吸の干渉、環境振動がすべて心臓信号に混入する。このノイズをリアルタイムで除去するには相当の計算資源が必要だ。5年前はその計算はクラウドで行われ、遅延が生じ持続的な接続が必要だった。今日では、低消費電力エッジチップ上の専用ニューラル処理ユニットが、サブ秒の遅延でローカルにて信号クリーニングと特徴量抽出アルゴリズムを実行できる。このエッジ推論へのシフトは、速さのみならずプライバシーの観点でも根本的な改善をもたらしている。
  </p>
  <p>
    <strong>第三に、最も重要なこととして、スケールのある訓練データの蓄積。</strong>睡眠AIのボトルネックはアルゴリズムではなく、ラベル付きデータだった。BCG波形からレム睡眠を認識するモデルを訓練するには、グラウンドトゥルースとして同時記録されたPSG+BCGの数千夜分が必要だ。2012年の大阪創業以来、日本・韓国・東南アジア全域の大学睡眠研究室との10年超の臨床連携を積み重ねてきたSleepTechの研究チームは、現在、学術病院研究機関以外では最大規模のペアリングされたBCG/PSGトレーニングデータセットの一つを保有している。このコーパスで訓練されたモデルは、体に一切の電極を付けることなく、通常の睡眠者において睡眠ステージ（覚醒、N1、N2、N3徐波睡眠、レム）をPSGに近い感度で識別できる。
  </p>

  <h2>AIが人間には見えないものを見る</h2>
  <p>
    AI睡眠解析の最も変革的な側面は、人間の判断を置き換えることではない。人間の観察者が維持できない時間分解能で、かつ無補助の知覚が捉えられる次元をはるかに超える変動の軸にわたって、継続的に動作する点にある。
  </p>
  <p>
    心臓インターバル解析を例に取ろう。人間の心臓はメトロノームのような機械的な規則性では鼓動しない。拍動間の間隔はミリ秒単位で変動し、そのパターンは自律神経系の状態の豊かな記述を符号化している。心拍変動（HRV）、すなわちその拍動間隔の統計的特徴付けは、40年以上にわたって健康指標として研究されてきた。しかし、ノイズの多いアンビエントセンサー信号から、体位変換・覚醒・睡眠ステージ転換を考慮しながら、一晩を通じて意味のあるHRVを計算することは、深層ニューラルネットワークのみが優雅に処理できる特徴エンジニアリングと学習済みパターン認識の問題だ。
  </p>
  <p>
    同様に、呼吸パターン解析がある。睡眠中の正常な呼吸は均一ではない。レム睡眠では速く深くなる。N3では遅くなる。軽度の睡眠関連呼吸障害を持つ個人では周期的なクラスタリングを示すことがある。ラベル付き呼吸データで訓練されたAIモデルは、周期性四肢運動のシグネチャを検出し、チェーンストークス呼吸の特徴的な漸増漸減パターン（心臓や神経学的問題に関連することがある徴候）を識別し、無呼吸イベントに先行する息継ぎ間隔の延長——イベントが臨床的に有意になる30〜90秒前のことが多い——にフラグを立てることができる。
  </p>
  <p>
    これらの解析はいずれも、リアルタイムに波形を見ている人間には解釈できない。ミリ秒精度の特徴量抽出、心臓・呼吸信号のクロスドメイン融合、集団ベースラインとの比較が必要であり、これらはすべて現代のAIアーキテクチャが自動的に実行する作業だ。
  </p>

