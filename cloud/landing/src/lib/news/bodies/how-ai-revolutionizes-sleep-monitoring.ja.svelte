  <h2>かつてクリニックが必要だったものを検出する</h2>
  <p>
    臨床的意義は大きい。閉塞性睡眠時無呼吸症（OSA）は世界で推定10億人に影響を与えているが、大多数は未診断だ。診断への従来の道筋——睡眠検査室でのPSG——は数百ドルから数千ドルを要し、臨床医の紹介が必要だ。承認デバイスによる在宅睡眠検査（HST）はコストが低いが、依然として機器の発送・返送が必要であり、完全な評価に必要な睡眠ステージング情報を欠いている。
  </p>
  <p>
    AIを活用したアンビエントセンサーはこのギャップを埋め始めている。毎晩の呼吸イベント指数（REI）、血中酸素飽和度の低下パターン（パルスオキシメトリと組み合わせた場合）、そして数週間の継続モニタリングにわたる睡眠断片化を計測するシステムは、バリデーション研究においてHSTに近い感度・特異度で、臨床的に有意なOSAを持つ可能性の高い個人を特定できる。これは診断ツールではない——医師の臨床的判断や正式な診断を置き換えることはできない——しかしスクリーニングツールとして、正式な評価を最も急ぐ必要がある人を特定できる。この集団レベルのスクリーニング機能だけでも、世界医学においてもっとも治療不足の状態の一つとされる疾患の診断格差を意味のある形で縮小できる可能性がある。
  </p>

  <h2>AIにまだできないこと</h2>
  <p>
    限界についての誠実さは信頼の前提条件だ。現在の非接触AI睡眠システムには、この分野がいまだ取り組んでいる意味のある限界がある。
  </p>
  <p>
    <strong>信号品質の劣化。</strong>体重が非常に大きい場合、極めて柔らかいマットレス、または厚いマットレストッパーは、BCG信号を使用可能な閾値以下に減衰させることがある。同じベッドで眠るパートナーは体動アーチファクトをもたらし、現代のデュアルゾーン構成で部分的に補正されるものの、単一センサーの精度を低下させることがある。
  </p>
  <p>
    <strong>集団の一般化可能性。</strong>主にアジア人集団サンプルで訓練されたモデルは（現在の大多数のデバイスがそうである）、著しく異なる心血管・呼吸プロファイルを持つ個人での精度が低下することがある。これは臨床AIで既知の問題であり、より多様なトレーニングデータセットによって取り組まれている。
  </p>
  <p>
    <strong>EEG相当のステージング。</strong>精密なN1/N2/N3/REM識別では、EEGは心肺代替信号より優れている。非接触システムは通常、深い統合睡眠とレムの識別で良好な感度を達成するが、N1検出は最も困難なステージングの問題として残っている。N1は生理学的に最も不均一なステージだからだ。
  </p>

  <h2>今後5年：何が来るか</h2>
  <p>
    いくつかの軌跡は明確だ。マルチモーダル融合——パッドからのBCGデータと、室内マイクからの音声（いびき検出と呼吸音解析）、ベッドサイドカメラからの赤外線モーション、オプションのリングや手首バンドからのウェアラブルPPGを組み合わせること——は、単一モダリティシステムが不得意とするエッジケースにわたって精度を大幅に改善する。
  </p>
  <p>
    縦断的健康変化検出は最も興奮される近期的応用だ。あなたの睡眠ベースラインを親密に知っているシステム——2年間毎晩計測してきたから——は、そのベースラインから統計的に意味のある乖離を、症状として現れる数週間前に検出できる。これは集団規模の慢性疾患早期警告であり、単発的な臨床スナップショットではなく、日常生活からの継続的な健康シグナルだ。
  </p>
  <p>
    大規模言語モデルの統合により、自然言語による睡眠コーチングが始まっている。複雑な睡眠パターンを非専門家に説明し、エビデンスに基づく行動的介入を提案し、パターンが臨床医との相談を示唆する場合にユーザーに通知する会話型インターフェースだ。これは臨床ケアの代替ではなく、睡眠専門医を訪れることが決してない何億もの人々にとって、生体データ解釈の認知的負担を軽減する高いスケーラビリティを持つ最初のステップだ。
  </p>

