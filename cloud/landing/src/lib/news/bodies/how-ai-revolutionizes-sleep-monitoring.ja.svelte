  <p>
    睡眠は、人間が毎晩行う最も複雑な生物学的プロセスの一つでありながら、歴史的にはもっとも観察されてこなかった行動でもある。目を閉じ、意識を失い、8時間後に目覚める。その間に何が実際に起きていたかについて、信頼できる情報はほとんど存在しなかった。この情報の空白が、今まさに解消されつつある。人工知能と新世代のアンビエントセンサー・マットレス下センサーの組み合わせが、臨床医・研究者・そして一般の人々に、5年前には存在しなかった睡眠への窓を提供し始めている。
  </p>

  <h2>AI以前の基準：かつて何を測定できたか</h2>
  <p>
    機械学習が寝室に参入する以前、睡眠評価には本質的に2つのルートが存在していた。ゴールドスタンダードはポリソムノグラフィー（PSG）だった。脳波（EEG）、眼球運動（EOG）、筋活動（EMG）、心拍数、血中酸素飽和度、呼吸努力を頭皮・顔・胸・脚に貼付した電極で同時に計測する、一泊の入院検査だ。PSGは網羅的で正確だが、すでに症状が現れて紹介状を得るほどの状態にあり、睡眠検査室の予約を数ヶ月待ち、臨床環境での睡眠を許容できる患者以外には、ほぼアクセスできない。
  </p>
  <p>
    第2のルートは消費者向けウェアラブル、すなわちリスト加速度計から睡眠を推定する活動量計やスマートウォッチだった。これらは利便性とコスト面で優れていたが、睡眠ステージ検出の信頼性は低く、2019年の<em>npj Digital Medicine</em>誌掲載の研究では、消費者向けリスト装着デバイスのPSGとの一致率はわずか65〜70%程度に過ぎず、特に浅い睡眠と深い睡眠の区別は不得意だった。これらは体動を睡眠の代替指標として用いており、直接的な生理学的計測ではなかった。
  </p>
  <p>
    この2つの極（網羅的な検査室と不正確なリストバンド）の間には、ほとんど何も存在しなかった。無呼吸向けの在宅睡眠検査は存在したが、呼吸データのみを取得し、完全な睡眠構造を計測するものではなかった。毎日継続できる、非臨床的な睡眠モニタリングという広大な中間領域は、ほぼ空白のままだった。
  </p>

