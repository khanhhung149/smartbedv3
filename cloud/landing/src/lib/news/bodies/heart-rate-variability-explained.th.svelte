  </blockquote>

  <h2>คณิตศาสตร์ของ HRV: RMSSD, SDNN และ LF/HF</h2>
  <p>
    มีหลายวิธีทางคณิตศาสตร์ที่ใช้วัด HRV โดยแต่ละวิธีเน้นด้านต่างๆ ของสรีรวิทยาพื้นฐาน ที่ใช้บ่อยที่สุดในอุปกรณ์สุขภาพสำหรับผู้บริโภคคือ <strong>RMSSD</strong> (รากที่สองของค่าเฉลี่ยกำลังสองของผลต่างต่อเนื่อง): รากที่สองของค่าเฉลี่ยของผลต่างกำลังสองระหว่างช่วงเวลาระหว่างการเต้นติดต่อกัน RMSSD มีความไวต่อการปรับของพาราซิมพาเทติก (เวกัส) โดยเฉพาะและตอบสนองต่อความเครียดเฉียบพลันหรือการฟื้นตัวได้อย่างรวดเร็ว ทำให้เหมาะสำหรับการติดตามรายวัน
  </p>
  <p>
    <strong>SDNN</strong> (ส่วนเบี่ยงเบนมาตรฐานของช่วง NN) จับความแปรปรวนโดยรวมรวมทั้งองค์ประกอบซิมพาเทติกและพาราซิมพาเทติก มักใช้ในบริบททางคลินิกมากกว่า โดยเฉพาะการติดตาม Holter 24 ชั่วโมง ซึ่งเป็นวิธีเดิมในการประเมิน HRV ในการศึกษาการแบ่งชั้นความเสี่ยงหัวใจ
  </p>
  <p>
    การวิเคราะห์โดเมนความถี่แยกสัญญาณ HRV ออกเป็นความถี่ส่วนประกอบ แถบ <strong>ความถี่ต่ำ (LF, ประมาณ 0.04–0.15 Hz)</strong> สะท้อนกิจกรรมซิมพาเทติกและพาราซิมพาเทติกผสมกัน แถบ <strong>ความถี่สูง (HF, ประมาณ 0.15–0.4 Hz)</strong> สอดคล้องอย่างใกล้ชิดกับความถี่การหายใจและสะท้อนกิจกรรมพาราซิมพาเทติก (เวกัส) เป็นหลัก อัตราส่วน LF/HF ถูกใช้เป็นดัชนีสมดุล sympathovagal
  </p>

