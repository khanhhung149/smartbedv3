  <h2>HRV ในระหว่างการนอนหลับ: สถาปัตยกรรมอัตโนมัติของคืน</h2>
  <p>
    การนอนหลับไม่ใช่การระงับการตื่นตัวแบบเฉื่อย แต่เป็นกระบวนการทางชีววิทยาที่กระตือรือร้นและมีการประสานงาน และระบบประสาทอัตโนมัติมีส่วนร่วมอย่างลึกซึ้งตลอดทั้งคืน HRV ระหว่างการนอนหลับบอกเรื่องราวที่ละเอียดอย่างน่าทึ่งเกี่ยวกับว่าร่างกายของคุณใช้คืนเพื่อฟื้นตัวได้ดีแค่ไหน
  </p>
  <p>
    ในระหว่าง <strong>ระยะ non-REM N1 และ N2</strong> (การนอนหลับเบา) กิจกรรมอัตโนมัติเริ่มเปลี่ยนจากความต้องการของการตื่นไปสู่การครอบงำของพาราซิมพาเทติกของการฟื้นตัวลึก HRV มักเพิ่มขึ้นเมื่อเทียบกับตอนตื่น เมื่อการถอนตัวของซิมพาเทติกทำให้ความตึงตัวของเวกัสเพิ่มขึ้น
  </p>
  <p>
    ในระหว่าง <strong>การนอนหลับลึก N3</strong> การครอบงำของพาราซิมพาเทติกอยู่ที่จุดสูงสุด อัตราการเต้นของหัวใจลดลงสู่จุดต่ำสุดของคืน HRV ถึงจุดสูงสุด การหายใจช้าลงและกลายเป็นปกติ นี่คือระยะที่เกิดการฟื้นฟูทางกายภาพที่ลึกที่สุด โกรทฮอร์โมนถูกปล่อยออกมาในพัลส์กลางคืนหลัก การซ่อมแซมเนื้อเยื่อเร่งขึ้น และระบบหัวใจและหลอดเลือดได้พักผ่อนลึกที่สุด HRV ระหว่าง N3 เป็นหนึ่งในตัวบ่งชี้คุณภาพการนอนหลับที่แข็งแกร่งที่สุดในแต่ละ epoch
  </p>
  <p>
    ในระหว่าง <strong>การนอนหลับ REM</strong> ภาพอัตโนมัติกลับกันอย่างน่าทึ่ง REM มีลักษณะความไม่เสถียรของระบบอัตโนมัติ อัตราการเต้นของหัวใจเพิ่มขึ้น อัตราการหายใจสูงขึ้นและไม่สม่ำเสมอ และ HRV ลดลงอย่างรวดเร็ว การระเบิดของกิจกรรมซิมพาเทติกเกิดขึ้นพร้อมกับการกระตุ้นเปลือกสมองที่รุนแรงซึ่งขับเคลื่อนการฝัน นี่ไม่ใช่พยาธิสภาพ แต่เป็นสรีรวิทยา REM ปกติ
  </p>

  <h2>SleepTech วัด HRV โดยไม่ต้องสัมผัสผิวหนังได้อย่างไร</h2>
  <p>
    การวัด HRV แบบดั้งเดิมต้องการ ECG (มาตรฐานทองคำ จับช่วง R-R โดยตรงจากกิจกรรมไฟฟ้าหัวใจ) หรือเซ็นเซอร์ photoplethysmography (PPG) ซึ่งก็คือ LED สีเขียวที่ด้านหลังของนาฬิกาอัจฉริยะส่วนใหญ่ ทั้งสองวิธีต้องสัมผัสร่างกายโดยตรง ระบบ YumePad ใช้หลักการทางฟิสิกส์ที่แตกต่างกันโดยพื้นฐาน: ballistocardiography (BCG) เมื่อหัวใจหดตัวและส่งเลือดเข้าสู่หลอดเลือดแดงใหญ่ แรงสะท้อนกลทางกลของการพ่นนั้น แม้เล็กน้อยแต่วัดได้ จะแพร่กระจายผ่านร่างกายไปยังพื้นผิวที่รองรับ เซ็นเซอร์แรงความไวสูงใต้ที่นอนตรวจจับการสั่นสะเทือนขนาดเล็กเหล่านี้
  </p>
  <p>
    ช่วงเวลาระหว่างการเต้นจะถูกประมาณจากจังหวะของยอดพีค J ที่ต่อเนื่องกัน สร้างสิ่งที่เรียกว่า "ช่วงเวลาระหว่างการเต้น BCG" (BCG-IBI) ด้วยการประมวลผลสัญญาณที่เหมาะสม BCG-IBI สามารถประมาณช่วง R-R ที่ได้จาก ECG ด้วยความแม่นยำเพียงพอสำหรับการวิเคราะห์ HRV ในบริบทการนอนหลับ การศึกษาตรวจสอบความถูกต้องอิสระที่เปรียบเทียบ HRV ที่ได้จาก BCG กับ ECG อ้างอิงพร้อมกันแสดงให้เห็นค่าเฉลี่ยของข้อผิดพลาดสัมบูรณ์ใน RMSSD ต่ำกว่า 5 ms ในสภาวะควบคุม ซึ่งอยู่ในช่วงที่มีความหมายทางคลินิกสำหรับการติดตามแนวโน้มตามแนวยาว
  </p>
  <p>
    วิธีการไม่สัมผัสนี้ไม่ใช่แค่ความสะดวกสบาย แต่ยังทำให้การวัดมีคุณภาพที่ PPG สวมใส่ที่ข้อมือไม่สามารถทำได้ในระหว่างการนอนหลับ: ผู้ใช้ไม่ต้องสวมใส่สิ่งใดเลย
  </p>

