  <h2>現代の課題：少子化、都市への移住、そして長寿化</h2>
  <p>
    伝統的な介護モデルを可能にしていた社会的基盤は、三つの収束する力によって侵食されています——人口動態の変化、経済的移住、そして文化的変化です。
  </p>
  <p>
    日本の合計特殊出生率は1970年代から2.1という置き換え水準を下回り続け、21世紀の多くの期間は1.2前後にとどまっています。算術的な結果は避けられません——はるかに多くの高齢者のケアを担う労働年齢の人々がはるかに少なくなっています。65歳以上の方に対する労働年齢人口の比率は1990年の約7:1から現在の約2:1に低下し、2040年までに1.5:1に近づく見込みです。日本には単純に、高齢化が進む人口規模の伝統的な介護モデルを支えるのに十分な人手がないのです。
  </p>
  <p>
    経済的な都市化は、人口動態の変化が構造的に生み出した物理的な分離を加速させました。戦後の数十年間、多くの高齢の親は近くに子どもがいる中で老いることができました。今日、成人した子どもたちは東京、大阪、名古屋などの主要都市に集中し、高齢の親は人口が大幅に減少した地方の県や小都市にとどまっています。別の都市や地域から高齢の親の幸福を管理する「遠距離介護」は、もはや稀で例外的な状況ではありません。それは日本の家族の大きく成長し続ける割合にとっての標準的な状況なのです。
  </p>
  <p>
    文化的変化はこれらの構造的な力を複雑にします。嫁が主要な高齢者ケアを提供するという期待は、女性の労働参加率の上昇とともに大幅に弱まりました。三世代同居家族は1980年の全世帯の約40%から現在の約10%まで減少しました。核家族が今では標準となっており、孝行への義務感は依然として強い（40代・50代の日本人が親の幸福に対して高い関心を示すことは調査で一貫して示されています）一方で、その義務を果たす構造的な手段は劇的に狭まっています。
  </p>

  <h2>テクノロジーは後継者ではなく、継続者として</h2>
  <p>
    高齢者ケアテクノロジーを伝統的な介護構造の崩壊に対する解決策として位置づけるリスクは、それが放棄の正当化になりえることです——センサーが見守っているから親は「ケアされている」と自分に言い聞かせながら、介護が求める人間の存在が依然として不在のまま、という状況です。
  </p>
  <p>
    SleepTechの創業チーム——その多くが日本の介護危機の真っ直中で育ったエンジニア、臨床家、デザイナーで構成されています——は、会社の創設当初からこのリスクについて明確に述べてきました。YumePadとスマートベッドのシステムは人間の存在を置き換えるためではなく、人間の注意の届く範囲を広げるために設計されました。この区別は非常に重要です。
  </p>
  <p>
